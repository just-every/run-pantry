// CONTRACT.md owns acceptance and status; these views never read each other.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseContract } from './seed-contract.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const cells = line => line.trim().slice(1, -1).split(/(?<!\\)\|/).map(x => x.trim().replaceAll('\\|', '|'))
// Preserve the displayed source text without introducing ambiguous repository
// references when prose joins words with a slash. Paths and URLs stay intact.
const proseReference = /(?<![\w./:@-])([A-Za-z][A-Za-z0-9_-]*)\/([A-Za-z][A-Za-z0-9_-]*)(?![\w./-])/g
const escapeHtml = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
const cell = value => String(value).replace(/`([^`]+)`/g, (span, code) => {
  proseReference.lastIndex = 0
  return proseReference.test(code) ? '<code>' + escapeHtml(code).replaceAll('/', '&#47;') + '</code>' : span
}).replace(proseReference, '$1&#47;$2').replaceAll('|', '\\|').replace(/\s*\n\s*/g, ' ').trim()
const table = (header, rows) => [header, '| ' + header.split('|').slice(1, -1).map(() => '---').join(' | ') + ' |', ...rows.map(row => '| ' + row.map(cell).join(' | ') + ' |')].join('\n')

export function contractDocuments(source) {
  const lines = source.replace(/\r\n?/g, '\n').split('\n')
  const start = lines.findIndex(line => /^\| Clause \| Title \| Kind \| Status \| Evidence \| Gap \|$/.test(line.trim()))
  if (start < 0) throw new Error('Missing canonical Status table')
  const rows = []
  for (let i = start + 2; i < lines.length && lines[i].trim().startsWith('|'); i++) rows.push(cells(lines[i]))
  const tally = selected => {
    const own = rows.filter(row => selected.includes(row[2]))
    return ['done', 'partial', 'missing'].map(status => own.filter(row => row[3] === status).length).concat(own.length)
  }
  // Repair derived summaries before the shared parser checks the whole source.
  const labels = { Published: ['published'], 'Target and push further': ['target', 'push-further'], All: ['published', 'target', 'push-further'] }
  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].startsWith('|')) continue
    const row = cells(lines[i])
    if (labels[row[0]]) lines[i] = '| ' + [row[0], ...tally(labels[row[0]])].join(' | ') + ' |'
  }
  const contract = lines.join('\n'), parsed = parseContract(contract)
  const evidence = new Map(rows.map(row => [row[0].replaceAll('`', ''), row[4]]))
  const { done, partial, missing, total } = parsed.counts
  const generated = '<!-- Generated by node src/base/contract-docs.mjs write. Edit CONTRACT.md. -->\n'
  const acceptance = generated + '# Pantry acceptance record\n\n'
    + `Source: [CONTRACT.md](CONTRACT.md). **Status: ${done} of ${total} clauses done, ${partial} partial, ${missing} missing.**\n\n`
    + 'Local assertions establish only their stated boundary. Hosted, provider and scale requirements retain their named missing proof in the Gap.\n\n'
    + table('| Clause | What a person can do | Evidence | Status | Gap |', parsed.clauses.map(c => [c.id, `**${c.title}.** ${c.text}`, evidence.get(c.id), c.status, c.gap])) + '\n'
  const claimStart = lines.indexOf('## Homepage claims'), claimEnd = lines.indexOf('## Status', claimStart)
  if (claimStart < 0 || claimEnd < 0) throw new Error('Missing homepage claim source')
  const claims = lines.slice(claimStart, claimEnd).filter(line => /^\| \d+ \|/.test(line)).map(cells)
  const byId = new Map(parsed.clauses.map(c => [c.id, c]))
  const claimRows = claims.map(([number, section, claim, ids, status]) => {
    const cited = ids.split(',').map(id => id.trim())
    for (const id of cited) if (!byId.has(id)) throw new Error(`Unknown claim clause ${id}`)
    return [number, section, claim, status, cited.map(id => `${id}: ${evidence.get(id)}`).join('; ')]
  })
  const claimDoc = generated + '# Pantry homepage claims → code\n\n'
    + 'The claim text and its boundary come from CONTRACT.md; the linked clauses supply current implementation evidence.\n\n'
    + table('| # | Section | Claim on the page | Status | Code path and evidence |', claimRows) + '\n'
  return new Map([['CONTRACT.md', contract], ['ACCEPTANCE.md', acceptance], ['docs/CLAIMS.md', claimDoc]])
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [command, ...extra] = process.argv.slice(2)
  if (!['write', 'check'].includes(command) || extra.length) throw new Error('Use contract-docs.mjs write or check')
  const stale = []
  for (const [name, output] of contractDocuments(readFileSync(resolve(root, 'CONTRACT.md'), 'utf8'))) {
    if (command === 'write') writeFileSync(resolve(root, name), output)
    else if (readFileSync(resolve(root, name), 'utf8') !== output) stale.push(name)
  }
  if (stale.length) throw new Error(`Stale generated contract docs: ${stale.join(', ')}; run node src/base/contract-docs.mjs write`)
  console.log(`Contract docs ${command}: passed`)
}
