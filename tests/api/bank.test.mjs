test('BANK-007 undo a newest-first reconciliation chain retains proofs, releases matches without posting, respects locks and grants, then reconciles again', async t => {
  const h = await harness(); t.after(() => h.close())
  const { acct } = await books(h)
  const bank = await h.command('bank-account.save', { name: 'Operating checking', institution: 'Chase', accountId: acct['1000'], numberLast4: '4821', openingDate: '2026-06-30', openingBalance: '0.00' })
  const statements = [], proofs = []
  for (const [index, month, end] of [[0, '07', '31'], [1, '08', '31'], [2, '09', '30']]) {
    const entry = await h.command('journal.save-draft', { date: `2026-${month}-10`, memo: `Design income ${month}`, lines: [{ accountId: acct['1000'], debit: '100.00' }, { accountId: acct['4000'], credit: '100.00' }] })
    await h.command('journal.post', { id: entry.id, revision: entry.revision })
    const imported = await h.command('statement.import', { bankAccountId: bank.id, fileName: `checking-${month}.csv`, content: `Posting Date,Description,Amount\n${month}/10/2026,DESIGN INCOME ${month},100.00\n`, opening: String(index * 100), closing: String((index + 1) * 100), start: `2026-${month}-01`, end: `2026-${month}-${end}`, confirmLast4: '4821' })
    const r = await h.view(`reconciliation/${imported.statement.id}`)
    await h.command('match.approve', { bankLineIds: [r.lines[0].id], journalLineIds: [at(r.postings, p => p.entry_date === `2026-${month}-10`).id] })
    const done = await h.command('reconciliation.complete', { statementId: imported.statement.id })
    statements.push(imported.statement); proofs.push(done.completed)
  }
  const accountant = await h.member('ann@example.test', 'accountant', { canReopen: true })
  const bookkeeper = await h.member('bea@example.test', 'bookkeeper')
  const before = await h.view('journal')
  let july = await h.view(`reconciliation/${statements[0].id}`, accountant)
  assert.deepEqual(july.undo.reconciliations.map(r => r.id), proofs.map(p => p.id).reverse())
  const undo = { statementId: statements[0].id, reason: 'July was matched to the wrong posting; repair all later proofs', reconciliationIds: july.undo.reconciliations.map(r => r.id) }
  await h.command('reconciliation.undo', undo, bookkeeper, 403)
  await h.command('reconciliation.undo', { ...undo, reason: '' }, accountant, 400)
  await h.command('reconciliation.undo', { ...undo, reconciliationIds: [proofs[0].id] }, accountant, 409)
  let close = await h.command('close.tasks', { period: '2026-09' })
  for (const task of close.tasks) close = await h.command('close.task', { id: task.id, revision: task.revision })
  await h.command('period.lock', { period: '2026-09' })
  july = await h.view(`reconciliation/${statements[0].id}`)
  assert.deepEqual(july.undo.locked.map(p => p.id), ['2026-09'])
  const locked = await h.send('/api/pantry/command/reconciliation.undo', undo, { cookie: accountant })
  assert.equal(locked.status, 409); assert.match(locked.value.error, /reopen|reopening/i)
  close = await h.command('period.request-reopen', { period: '2026-09', reason: undo.reason }, bookkeeper)
  await h.command('period.decide-reopen', { id: close.requests[0].id, decision: 'approve' }, accountant)
  const undone = await h.command('reconciliation.undo', undo, accountant)
  assert.deepEqual(undone.undone, proofs.map(p => p.id).reverse())
  assert.deepEqual(await h.view('journal'), before, 'reconciliation undo changes no postings')
  for (const [index, statement] of statements.entries()) {
    const r = await h.view(`reconciliation/${statement.id}`)
    assert.equal(r.completed, null)
    assert.equal(r.history[0].id, proofs[index].id)
    assert.equal(r.history[0].undo_id, undone.id)
    assert.deepEqual(r.history[0].snapshot.reconciliation.proof, JSON.parse(proofs[index].proof))
    assert.equal(r.history[0].snapshot.statement.document_id, statement.document_id)
    const document = await h.send(`/api/pantry/documents/${statement.document_id}`, undefined, { cookie: accountant })
    assert.equal(document.status, 200)
    assert.equal(at((await h.view(`close/${statement.end_date.slice(0, 7)}`)).checks, x => x.key === 'bank').ok, false)
  }
  assert.equal((await h.view('activity')).audit.filter(a => a.action === 'reconciliation.undo').length, 3)
  const pack = await h.view('package/2026-09?basis=accrual')
  assert.equal(pack.voidedReconciliations.length, 3)
  // Correct July's link to the same existing posting: no reversal or replacement posting is required.
  july = await h.view(`reconciliation/${statements[0].id}`)
  await h.command('match.undo', { id: july.lines[0].match_id, reason: 'Review the match after reopening' })
  assert.deepEqual(await h.view('journal'), before)
  await h.command('match.approve', { bankLineIds: [july.lines[0].id], journalLineIds: [july.postings[0].id] })
  for (const [index, statement] of statements.entries()) {
    const repaired = await h.command('reconciliation.complete', { statementId: statement.id })
    assert.notEqual(repaired.completed.id, proofs[index].id)
    assert.equal(repaired.history.length, 1)
    assert.equal(at((await h.view(`close/${statement.end_date.slice(0, 7)}`)).checks, x => x.key === 'bank').ok, true)
  }
  await h.command('reconciliation.undo', undo, accountant, 409)
})
