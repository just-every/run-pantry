import assert from 'node:assert/strict'
import { at, books } from './harness.mjs'

export async function access003Journey(h) {
  const { acct } = await books(h), day = new Date().toISOString().slice(0, 10)
  const book = await h.member('bea@example.test', 'bookkeeper', { canPost: true })
  const accountant = await h.member('ann@example.test', 'accountant', { canPost: true })
  const noPost = await h.member('cal@example.test', 'bookkeeper')
  const c = await h.command('contact.save', { kind: 'customer', name: 'Cedar Design', email: 'billing@cedar.example', termsDays: 30 })
  const line = amount => ({ description: 'Design services', quantity: '1', rate: amount, accountId: acct['4000'], taxCode: 'exempt' })
  const draft = (amount, extra = {}, cookie = book) => h.command('invoice.save-draft', { customerId: c.id, issueDate: day, lines: [line(amount)], ...extra }, cookie)
  const limit = async (cookie = book) => (await h.view('state', cookie)).settings.issuingLimits.effective
  const saveLimit = async (id, issuing, credit, extra = {}) => {
    const current = (await h.view('state')).settings.issuingLimits.rows.find(r => r.id === id)
    return h.command('issuing-limit.save', { id, issuing, credit, revision: current?.revision, ...extra })
  }
  const self = async (d, status = 200, cookie = book, revision) => h.command('invoice.approve-issue', { id: d.id, revision: d.revision, limitRevision: revision ?? (await limit(cookie))?.revision }, cookie, status)
  const current = async id => at((await h.view('sales')).invoices, i => i.id === id)
  let d = await draft('1800.00')
  await self(d, 403) // default none
  await h.command('invoice.approve', { id: d.id, revision: d.revision }, book, 403)
  await h.command('issuing-limit.save', { id: 'role:bookkeeper', issuing: '2500', credit: '200' }, book, 403)
  await saveLimit('role:bookkeeper', '2500', '200')
  await saveLimit('person:ann@example.test', '1900', '100')
  const issued = await self(d)
  assert.equal(issued.status, 'issued'); assert.ok(issued.journal_id)
  const provenance = JSON.parse(issued.self_approval)
  assert.deepEqual([provenance.limit, provenance.source, provenance.person], [250000, 'role', 'bea@example.test'])
  const history = await h.view(`activity?record=${d.id}`)
  const event = at(history.audit, e => e.action === 'invoice.approve')
  const detail = JSON.parse(event.detail)
  assert.equal(detail.label, 'self-approved within limit'); assert.equal(detail.limitRevision, provenance.limitRevision)
  assert.equal(at(history.audit, e => e.action === 'invoice.issue').approval.actor_email, 'bea@example.test')
  assert.ok((await h.view('self-approved?day=' + day + '&person=bea%40example.test')).documents.some(x => x.id === d.id))
  assert.equal((await h.view('self-approved?day=' + day + '&person=ann%40example.test')).documents.length, 0)
  await h.view('self-approved?day=' + day, book, 403)
  await h.command('invoice.save-draft', { id: issued.id, revision: issued.revision, customerId: c.id, issueDate: day, lines: [line('1800')] }, book, 409)
  const over = await draft('3200.00'); await self(over, 403)
  const ownerApproved = await h.command('invoice.approve', { id: over.id, revision: over.revision })
  const target = await h.command('invoice.issue', { id: over.id })
  assert.equal(target.status, 'issued'); assert.equal(target.self_approval, null)
  const small = await draft('150', { kind: 'credit', creditFor: target.id }); assert.equal((await self(small)).status, 'issued')
  const large = await draft('400', { kind: 'credit', creditFor: target.id }); await self(large, 403)
  const correction = await draft('50', { kind: 'credit', creditFor: issued.id }); await self(correction, 403)
  const approvedCorrection = await h.command('invoice.approve', { id: correction.id, revision: correction.revision })
  assert.equal((await h.command('invoice.issue', { id: approvedCorrection.id })).status, 'issued')
  const stale = await draft('900'), oldLimit = await limit()
  await saveLimit('role:bookkeeper', '2000', '200'); await self(stale, 409, book, oldLimit.revision)
  await saveLimit('role:bookkeeper', '', ''); await self(stale, 409, book, oldLimit.revision)
  assert.equal((await current(stale.id)).status, 'draft')
  await saveLimit('role:bookkeeper', '2500', '200')
  await saveLimit('person:bea@example.test', '0.00', '0.00')
  assert.equal((await limit()).issuing_cents, 0); await self(stale, 403)
  await saveLimit('person:bea@example.test', '', '', { inherit: true }); assert.equal((await limit()).id, 'role:bookkeeper')
  const ownOverride = await draft('1800', {}, accountant); assert.equal((await self(ownOverride, 200, accountant)).status, 'issued')
  const aboveOverride = await draft('2000', {}, accountant); await self(aboveOverride, 403, accountant)
  const noGrant = await draft('50', {}, noPost); await self(noGrant, 403, noPost)
  await h.command('invoice.approve-issue', { id: stale.id, revision: 'stale', limitRevision: (await limit()).revision }, book, 409)
  const agent = await h.agent('limits-agent')
  assert.equal((await h.send('/api/pantry/command/invoice.approve-issue', { id: stale.id, revision: stale.revision }, { headers: { authorization: `Bearer ${agent.token}` } })).status, 401)
  // Total basis includes tax and delivery, after discounts; deposits and early offers do not lower it.
  const tax = await h.command('tax-code.save', { name: 'Sales tax', state: 'NY', rate: '10', accountId: acct['2200'] })
  const taxed = await draft('2400', { lines: [{ ...line('2400'), taxCode: tax.id }] }); await self(taxed, 403)
  await h.command('discount-settings.save', { discountAccountId: acct['4000'] })
  const discounted = await draft('2600', { discounts: [{ type: 'amount', value: '200' }] })
  assert.equal(discounted.total_cents, 240000); assert.equal((await self(discounted)).status, 'issued')
  const bank = await h.command('bank-account.save', { name: 'Operating checking', institution: 'Community Bank', accountId: acct['1000'], numberLast4: '4821', openingDate: '2026-01-01', openingBalance: '0' })
  const deposit = await draft('3000', { deposit: { amount: '1000', bankAccountId: bank.id, method: 'check' } }); await self(deposit, 403)
  const early = await draft('1800', { earlyPayment: { percent: '2', days: 10 } }); const earlyIssued = await self(early)
  await h.command('payment.record', { direction: 'received', contactId: c.id, date: day, amount: '1764', bankAccountId: bank.id, method: 'check', allocations: [{ targetId: early.id, amount: '1764' }] }, book)
  const credit = at((await h.view('sales')).invoices, x => x.early_discount && x.credit_for === early.id)
  const discountDetail = credit.early_detail
  assert.equal(discountDetail.approval, (await h.view(`activity?record=${early.id}`)).approvals.find(a => a.subject_revision === early.revision).id)
  assert.equal((await current(earlyIssued.id)).open_cents, 0)
  // The same public command transport governs per-occurrence templates and prices.
  const template = async amount => h.command('recurring.save', { customerId: c.id, startDate: '2027-01-01', every: 1, unit: 'month', mode: 'send', lines: [line(amount)] }, book)
  const within = await template('1800')
  assert.equal((await h.command('recurring.approve', { id: within.id, revision: within.revision, limitRevision: (await limit()).revision }, book)).status, 'active')
  const above = await template('3200')
  await h.command('recurring.approve', { id: above.id, revision: above.revision, limitRevision: (await limit()).revision }, book, 403)
  assert.equal((await h.command('recurring.approve', { id: above.id, revision: above.revision })).status, 'active')
  for (const [amount, effectiveDate, status] of [['1900', '2027-02-01', 200], ['3200', '2027-03-01', 403]]) {
    const price = await h.command('recurring.price', { id: within.id, revision: within.revision, effectiveDate, lines: [line(amount)] }, book)
    await h.command('recurring.approve-price', { id: price.id, revision: price.revision, templateRevision: within.revision, limitRevision: (await limit()).revision }, book, status)
  }
  const changes = (await h.view('activity?kind=issuing-limit')).audit.map(x => JSON.parse(x.detail))
  assert.ok(changes.some(x => x.before?.issuing_cents === 250000 && x.after?.issuing_cents === 200000))
}
