test('INVOICE-009 customer records edit contacts and defaults, show every current record and email outcome, and drill through at 1440 and 390', async t => {
  const app = await providerWorker({ clock: true, bindings: {}, outbound: async request => {
    const url = new URL(request.url)
    assert.equal(url.hostname, 'api.stripe.com')
    assert.equal(url.pathname, '/v1/account')
    return Response.json({ id: 'acct_customer_record', country: 'US', default_currency: 'usd', business_profile: { name: 'Juniper Lane Design' } })
  } }); t.after(() => app.close())
  const browser = await chromium.launch({ headless: true, args: ['--use-mock-keychain', '--password-store=basic'] }); t.after(() => browser.close())
  const owner = await browser.newContext({extraHTTPHeaders:{'x-synthetic-pantry-clock':'2026-10-30T12:00:00Z'}})
  assert.equal((await owner.request.post(`${app.origin}/auth/bootstrap`, { headers: { origin: app.origin }, data: { token: TOKEN, displayName: 'Rosa Rivera' }, maxRedirects: 0 })).status(), 303)
  await owner.request.post(`${app.origin}/setup`, { headers: { origin: app.origin }, form: { confirm: 'yes' }, maxRedirects: 0 })
  const command = async (op, data) => { const r = await owner.request.post(`${app.origin}/api/pantry/command/${op}`, { headers: { origin: app.origin }, data }); assert.equal(r.status(), 200, `${op}: ${await r.text()}`); return r.json() }
  const view = async path => { const r = await owner.request.get(`${app.origin}/api/pantry/${path}`); assert.equal(r.status(), 200, await r.text()); return r.json() }
  await command('entity.save', { legalName: 'Juniper Lane Design LLC', entityType: 'single-member-llc', state: 'NY', fiscalYearStart: 1, taxMethod: 'cash', booksStart: '2026-01-01', policies: '' })
  await command('chart.start', {})
  await command('stripe.connect', { secretKey: 'synthetic-pantry-1003' })
  const state = await view('state'), acct = Object.fromEntries(state.accounts.map(a => [a.code, a.id]))
  const bank = await command('bank-account.save', { name: 'Operating checking', institution: 'Chase', accountId: acct['1000'], numberLast4: '4821', openingDate: '2026-01-01', openingBalance: '0.00' })
  const storageState = await owner.storageState()
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ storageState, extraHTTPHeaders:{'x-synthetic-pantry-clock':'2026-10-30T12:00:00Z'}, viewport: { width, height: width === 390 ? 844 : 1000 } })
    const page = await context.newPage(), errors = []; page.on('pageerror', e => errors.push(String(e)))
    const name = `Cedar Studio ${width}`, notes = `Internal purchasing review ${width}`
    await page.goto(`${app.origin}/app/sales?tab=contacts`)
    await page.getByLabel('Name', { exact: true }).fill(name)
    await page.getByLabel('Email', { exact: true }).fill(`studio-${width}@example.test`)
    await page.getByLabel('Payment terms (days)', { exact: true }).fill('45')
    await page.getByLabel('Phone', { exact: true }).fill('212 555 0140')
    await page.getByLabel('Billing address', { exact: true }).fill('18 Cedar Street, New York NY 10001')
    await page.getByLabel('Service address', { exact: true }).fill('40 Studio Lane, Brooklyn NY 11201')
    await page.getByLabel('Internal notes', { exact: true }).fill(notes)
    await page.getByLabel('All available methods', { exact: true }).uncheck()
    await page.getByLabel('Bank account (ACH)', { exact: true }).uncheck()
    await page.getByRole('button', { name: 'Add contact person', exact: true }).click()
    await page.getByLabel('Contact 1 name', { exact: true }).fill('Maya Chen')
    await page.getByLabel('Contact 1 email', { exact: true }).fill(`maya-${width}@example.test`)
    await page.getByLabel('Contact 1 phone', { exact: true }).fill('212 555 0141')
    await page.getByLabel('Contact 1 primary', { exact: true }).check()
    await page.getByRole('button', { name: 'Add contact person', exact: true }).click()
    await page.getByLabel('Contact 2 name', { exact: true }).fill('Jordan Kim')
    await page.getByLabel('Contact 2 email', { exact: true }).fill(`jordan-${width}@example.test`)
    await page.getByLabel('Contact 2 billing', { exact: true }).uncheck()
    await page.getByLabel('Contact 2 cc', { exact: true }).check()
    await page.screenshot({ path: `/tmp/sx-pantry-r12-customer-edit-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Add', exact: true }).click()
    await page.getByRole('heading', { name: `${name} · customer history`, exact: true }).waitFor()
    await page.reload()
    await page.getByRole('heading', { name: `${name} · customer history`, exact: true }).waitFor()
    await page.getByRole('button', { name: 'Edit contact details', exact: true }).click()
    await page.getByLabel('Phone', { exact: true }).fill('212 555 0142')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await page.getByRole('button', { name: 'Edit contact details', exact: true }).waitFor()
    const customer = (await view('state')).contacts.find(c => c.name === name)
    assert.ok(customer)
    assert.equal(customer.phone, '212 555 0142')
    const draft = await command('invoice.save-draft', { customerId: customer.id, issueDate: '2026-09-01', lines: [{ description: 'Autumn design retainer', quantity: '1', rate: '2400.00', accountId: acct['4000'], taxCode: 'exempt' }] })
    assert.equal(draft.due_date, '2026-10-16', 'customer default terms apply to the next invoice')
    await command('invoice.approve', { id: draft.id, revision: draft.revision })
    const inv = await command('invoice.issue', { id: draft.id })
    const credit = await command('invoice.save-draft', { customerId: customer.id, kind: 'credit', creditFor: inv.id, issueDate: '2026-09-10', lines: [{ description: 'Design scope reduction', quantity: '1', rate: '200.00', accountId: acct['4000'], taxCode: 'exempt' }] })
    await command('invoice.approve', { id: credit.id, revision: credit.revision }); await command('invoice.issue', { id: credit.id })
    await command('payment.record', { direction: 'received', contactId: customer.id, date: '2026-09-15', amount: '500.00', bankAccountId: bank.id, reference: `CEDAR-${width}`, allocations: [{ targetId: inv.id, amount: '500.00' }] })
    await page.goto(`${app.origin}/app/sales`)
    await page.getByRole('row').filter({ has: page.getByText(inv.number, { exact: true }) }).click()
    assert.deepEqual((await page.getByLabel('Send to', { exact: true }).inputValue()).split(',').map(s => s.trim()).sort(), [`jordan-${width}@example.test`, `maya-${width}@example.test`])
    await page.getByRole('button', { name: 'Send invoice', exact: true }).click()
    await page.getByText('Not sent: local run', { exact: true }).first().waitFor()
    await page.screenshot({ path: `/tmp/sx-pantry-r12-invoice-send-${width}.png`, fullPage: true })
    const sales = await view('sales'), sent = { deliveries: sales.deliveries.filter(d => d.invoice_id === inv.id) }
    const customerContext = await browser.newContext({ extraHTTPHeaders:{'x-synthetic-pantry-clock':'2026-10-30T12:00:00Z'}, viewport: { width, height: width === 390 ? 844 : 1000 } }), hosted = await customerContext.newPage()
    await hosted.goto(`${app.origin}/i/${sales.invoices.find(i => i.id === inv.id).link_token}`)
    await hosted.getByRole('button', { name: 'Pay by card', exact: true }).waitFor()
    assert.equal(await hosted.getByRole('button', { name: 'Pay by bank account (ACH)', exact: true }).count(), 0)
    await hosted.getByRole('heading', { name: 'How to pay', exact: true }).waitFor()
    assert.ok(!(await hosted.locator('body').innerText()).includes(notes))
    assert.equal(await hosted.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await hosted.screenshot({ path: `/tmp/sx-pantry-r12-customer-hosted-${width}.png`, fullPage: true })
    await customerContext.close()
    assert.deepEqual(sent.deliveries.map(d => d.recipient).sort(), [`jordan-${width}@example.test`, `maya-${width}@example.test`])
    assert.ok(sent.deliveries.every(d => d.status === 'suppressed'), 'local mail outcomes are honest')
    await command('exemption.save', { customerId: customer.id, certificateNumber: `NY-CEDAR-${width}`, states: ['NY'], validFrom: '2026-01-01', expiresOn: '2027-12-31', name: `Cedar-certificate-${width}.txt`, mediaType: 'text/plain', base64: Buffer.from(`Cedar Studio NY exemption ${width}`).toString('base64') })
    await page.goto(`${app.origin}/app/sales?tab=contacts&customer=${customer.id}`)
    const history = await view(`customers/${customer.id}`)
    assert.equal(history.summary.open_balance_cents, 170000)
    const aging = await view(`reports/receivables?to=${history.asOf}`)
    assert.equal(aging.items.filter(r => r.contact_id === customer.id).reduce((n, r) => n + r.open, 0), history.summary.open_balance_cents)
    await page.getByRole('heading', { name: `${name} · customer history`, exact: true }).waitFor()
    const historyCard = page.locator('.card').filter({ has: page.getByRole('heading', { name: `${name} · customer history`, exact: true }) })
    await historyCard.getByText(notes, { exact: true }).waitFor()
    await historyCard.getByText('18 Cedar Street, New York NY 10001', { exact: true }).waitFor()
    await historyCard.getByText('40 Studio Lane, Brooklyn NY 11201', { exact: true }).waitFor()
    await historyCard.getByText('45 days', { exact: true }).first().waitFor()
    await historyCard.getByText('Card, Offline payment instructions', { exact: true }).waitFor()
    await page.getByRole('heading', { name: 'Customer email history', exact: true }).waitFor()
    assert.equal(await page.getByText('suppressed', { exact: true }).count(), 2)
    await page.getByRole('link', { name: `Cedar-certificate-${width}.txt`, exact: true }).waitFor()
    const certificate = await context.request.get(`${app.origin}/api/pantry/documents/${history.certificates[0].document_id}`)
    assert.equal(await certificate.text(), `Cedar Studio NY exemption ${width}`)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `record fits ${width}`)
    await page.screenshot({ path: `/tmp/sx-pantry-r12-customer-history-${width}.png`, fullPage: true })
    await historyCard.screenshot({ path: `/tmp/sx-pantry-r12-customer-card-${width}.png` })
    await page.locator('.card').filter({ has: page.getByRole('heading', { name: 'Customer email history', exact: true }) }).screenshot({ path: `/tmp/sx-pantry-r12-customer-mail-${width}.png` })
    for (const row of history.rows) {
      await page.getByRole('link', { name: `${row.kind === 'credit' ? 'Credit' : row.kind === 'payment' ? 'Payment' : 'Invoice'} ${row.reference}`, exact: true }).first().click()
      await page.getByRole('heading', { name: row.kind === 'payment' ? new RegExp('Payment') : new RegExp(row.reference) }).first().waitFor()
      assert.equal(await page.getByText('Something went wrong').count(), 0)
      await page.screenshot({ path: `/tmp/sx-pantry-r12-customer-${row.kind}-${width}.png`, fullPage: true })
      await page.goto(`${app.origin}/app/sales?tab=contacts&customer=${customer.id}`)
      await page.getByRole('heading', { name: `${name} · customer history`, exact: true }).waitFor()
    }
    await statementsBrowser({ page, context, customer, width, origin: app.origin, history })
    await lateFeeBrowser({ page, context, invoice: inv, width, origin: app.origin, accountId: acct['4000'] })
    await refundsBrowser({page,width,origin:app.origin,command,view,customer,acct,bank})
    await voidBrowser({page,width,origin:app.origin,command,view,customer,acct})
    await approvedAdjustmentsBrowser({ page, context, width, origin: app.origin, command, view, customer, acct, bank })
    await page.getByRole('link', { name: 'Reconcile with receivables aging', exact: true }).click()
    await page.getByRole('heading', { name: /^Receivables aging/ }).waitFor()
    assert.deepEqual(errors, [], `no page errors at ${width}`)
    await context.close()
  }
  await browser.close()
  await remindersJourney(t)
  await paymentStatusBrowser(t)
  await autopayBrowser(t)
  await textingBrowser(t)
})
