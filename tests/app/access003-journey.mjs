import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium, expect } from '@playwright/test'
import { providerWorker } from './provider-worker.mjs'
import { TOKEN } from './worker.mjs'

export async function access003Browser(t) {
  const evidence = process.env.PANTRY_EVIDENCE_DIR || '/tmp/pantry-access003'
  await mkdir(evidence, { recursive: true })
  const mail = []
  const app = await providerWorker({ bindings: { MAIL_PROVIDER: 'resend', MAIL_API_KEY: 'synthetic-mail-key' }, outbound: async request => {
    assert.equal(new URL(request.url).hostname, 'api.resend.com'); mail.push(await request.json()); return Response.json({ id: `mail-${mail.length}` })
  } }); t.after(() => app.close())
  const browser = await chromium.launch({ headless: true, args: ['--use-mock-keychain', '--password-store=basic'] }); t.after(() => browser.close())
  const owner = await browser.newContext(); t.after(() => owner.close())
  const { origin } = app
  assert.equal((await owner.request.post(`${origin}/auth/bootstrap`, { headers: { origin }, data: { token: TOKEN, displayName: 'Olivia Owner' }, maxRedirects: 0 })).status(), 303)
  await owner.request.post(`${origin}/setup`, { headers: { origin }, form: { confirm: 'yes' }, maxRedirects: 0 })
  const cmd = context => async (op, data, status = 200) => { const r = await context.request.post(`${origin}/api/pantry/command/${op}`, { headers: { origin }, data }); assert.equal(r.status(), status, `${op}: ${await r.text()}`); return r.json() }
  const command = cmd(owner)
  const view = async (context, path) => (await context.request.get(`${origin}/api/pantry/${path}`)).json()
  await command('entity.save', { legalName: 'Juniper Lane Design LLC', entityType: 'single-member-llc', state: 'NY', fiscalYearStart: 1, taxMethod: 'cash', booksStart: '2026-01-01' })
  await command('chart.start', {})
  const state = await view(owner, 'state'), income = state.accounts.find(a => a.code === '4000').id
  for (const width of [1440, 390]) {
    const email = `bea${width}@example.test`, customer = await command('contact.save', { kind: 'customer', name: `Cedar Studio ${width}`, email: `billing${width}@cedar.example`, termsDays: 30 })
    await command('member.save', { name: `Bea ${width}`, email, role: 'bookkeeper', canPost: true })
    const member = await browser.newContext({ viewport: { width, height: 1000 } }); t.after(() => member.close())
    const message = mail.findLast(m => [m.to].flat().includes(email)), token = new URL(message.text.match(/http:\/\/[^\s]+\/auth\/confirm\?token=[^\s]+/)[0]).searchParams.get('token')
    assert.equal((await member.request.post(`${origin}/auth/confirm`, { headers: { origin }, data: { token }, maxRedirects: 0 })).status(), 303)
    const book = cmd(member), page = await member.newPage(), settings = await owner.newPage()
    await settings.setViewportSize({ width, height: 1000 })
    await settings.goto(`${origin}/app/settings`)
    const limits = settings.locator('section.card').filter({ has: settings.getByRole('heading', { name: 'Issuing limits', exact: true }) })
    await limits.getByLabel('Limit for', { exact: true }).selectOption('role:bookkeeper')
    await limits.getByLabel('Invoice issuing limit (USD)', { exact: true }).fill('2500.00')
    await limits.getByLabel('Credit limit (USD)', { exact: true }).fill('200.00')
    await Promise.all([settings.waitForResponse(r => r.url().endsWith('/command/issuing-limit.save') && r.status() === 200), limits.getByRole('button', { name: 'Save issuing limits', exact: true }).click()])
    await expect(limits.getByRole('cell', { name: '$2,500.00', exact: true })).toBeVisible()
    await limits.screenshot({ path: `${evidence}/access003-settings-${width}.png` })
    const line = amount => ({ description: 'Brand design services', quantity: '1', rate: amount, accountId: income, taxCode: 'exempt' })
    const draft = (amount, extra = {}, action = book) => action('invoice.save-draft', { customerId: customer.id, issueDate: '2026-10-21', lines: [line(amount)], ...extra })
    const d = await draft('1800')
    const choose = async item => { await page.goto(`${origin}/app/sales`); await page.getByRole('row').filter({ hasText: item.number }).click() }
    await choose(d)
    await page.getByRole('button', { name: 'Approve and issue within limit', exact: true }).click()
    await expect(page.getByText(/Self-approved within limit ·/)).toBeVisible()
    await page.screenshot({ path: `${evidence}/access003-issued-${width}.png`, fullPage: true })
    assert.equal(await page.getByRole('button', { name: 'Edit', exact: true }).count(), 0)
    const over = await draft('3200'); await choose(over)
    assert.equal(await page.getByRole('button', { name: 'Approve and issue within limit', exact: true }).count(), 0)
    await expect(page.getByText(/Approval needs the posting grant/)).toBeVisible()
    await page.screenshot({ path: `${evidence}/access003-second-person-${width}.png`, fullPage: true })
    const targetDraft = await draft('5000', {}, command)
    await command('invoice.approve', { id: targetDraft.id, revision: targetDraft.revision }); await command('invoice.issue', { id: targetDraft.id })
    const credit = await draft('150', { kind: 'credit', creditFor: targetDraft.id }); await choose(credit)
    await page.getByRole('button', { name: 'Approve and issue within limit', exact: true }).click()
    await expect(page.getByText(/Self-approved within limit ·/)).toBeVisible()
    const large = await draft('400', { kind: 'credit', creditFor: targetDraft.id }); await choose(large)
    assert.equal(await page.getByRole('button', { name: 'Approve and issue within limit', exact: true }).count(), 0)
    const own = await draft('50', { kind: 'credit', creditFor: d.id }); await choose(own)
    assert.equal(await page.getByRole('button', { name: 'Approve and issue within limit', exact: true }).count(), 0)
    const stale = await draft('900'); await choose(stale)
    await expect(page.getByRole('button', { name: 'Approve and issue within limit', exact: true })).toBeVisible()
    await limits.getByLabel('Invoice issuing limit (USD)', { exact: true }).fill('0')
    await limits.getByRole('button', { name: 'Save issuing limits', exact: true }).click()
    await expect(limits.getByRole('cell', { name: 'No self-approval', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Approve and issue within limit', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText(/limit changed.*reload/i)
    await page.screenshot({ path: `${evidence}/access003-revoked-${width}.png`, fullPage: true })
    await limits.getByLabel('Invoice issuing limit (USD)', { exact: true }).fill('2500')
    await limits.getByRole('button', { name: 'Save issuing limits', exact: true }).click()
    await expect(limits.getByRole('cell', { name: '$2,500.00', exact: true })).toBeVisible()
    const template = await book('recurring.save', { customerId: customer.id, startDate: '2027-01-01', every: 1, unit: 'month', mode: 'send', lines: [line('1800')] })
    await page.goto(`${origin}/app/sales`); await page.getByRole('tab', { name: 'Recurring', exact: true }).click()
    await page.getByRole('row').filter({ hasText: template.number }).click()
    await page.getByRole('button', { name: 'Approve automatic sending', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Approve automatic sending', exact: true })).toHaveCount(0)
    const price = await book('recurring.price', { id: template.id, revision: template.revision, effectiveDate: '2027-02-01', lines: [line('1900')] })
    await page.reload(); await page.getByRole('tab', { name: 'Recurring', exact: true }).click(); await page.getByRole('row').filter({ hasText: template.number }).click()
    await page.getByRole('button', { name: 'Approve this price', exact: true }).click()
    await expect(page.getByText(`Approved by Bea ${width}`, { exact: true })).toBeVisible()
    await page.screenshot({ path: `${evidence}/access003-recurring-${width}.png`, fullPage: true })
    await settings.reload()
    await limits.getByLabel('Prepared by', { exact: true }).selectOption(email)
    await expect(limits.getByRole('row').filter({ hasText: d.number })).toBeVisible()
    await expect(limits.getByRole('row').filter({ hasText: over.number })).toHaveCount(0)
    await limits.screenshot({ path: `${evidence}/access003-daily-${width}.png` })
    await page.goto(`${origin}/app/activity`)
    await page.getByLabel('Record ID', { exact: true }).fill(d.id)
    await page.getByRole('button', { name: 'Filter activity', exact: true }).click()
    for (const summary of await page.getByText('Inspect history', { exact: true }).all()) await summary.click()
    await expect(page.getByText('self-approved within limit', { exact: true })).toBeVisible()
    await page.screenshot({ path: `${evidence}/access003-activity-${width}.png`, fullPage: true })
    await page.close(); await settings.close(); await member.close()
  }
}
