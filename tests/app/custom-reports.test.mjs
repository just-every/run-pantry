import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { chromium } from '@playwright/test'
import { TOKEN } from './worker.mjs'
import { providerWorker } from './provider-worker.mjs'

test('REPORT-005 / REPORT-006 build and reopen a role-shared gross-margin layout, choose bases and export a combined management PDF at 1440 and 390', async t => {
  const evidence = process.env.PANTRY_EVIDENCE_DIR || '/tmp/sx-pantry-r17'
  await (await import('node:fs/promises')).mkdir(evidence, { recursive: true })
  const app = await providerWorker({ bindings: {}, outbound: async request => assert.fail(`Unexpected provider ${new URL(request.url).hostname}`) }); t.after(() => app.close())
  const browser = await chromium.launch({ headless: true, args: ['--use-mock-keychain', '--password-store=basic'] }); t.after(() => browser.close())
  const owner = await browser.newContext()
  assert.equal((await owner.request.post(`${app.origin}/auth/bootstrap`, { headers: { origin: app.origin }, data: { token: TOKEN, displayName: 'Rosa Rivera' }, maxRedirects: 0 })).status(), 303)
  await owner.request.post(`${app.origin}/setup`, { headers: { origin: app.origin }, form: { confirm: 'yes' }, maxRedirects: 0 })
  const command = async (op, data) => { const r = await owner.request.post(`${app.origin}/api/pantry/command/${op}`, { headers: { origin: app.origin }, data }); assert.equal(r.status(), 200, `${op}: ${await r.text()}`); return r.json() }
  const view = async path => { const r = await owner.request.get(`${app.origin}/api/pantry/${path}`); assert.equal(r.status(), 200, await r.text()); return r.json() }
  await command('entity.save', { legalName: 'Juniper Lane Design LLC', entityType: 'single-member-llc', state: 'NY', fiscalYearStart: 1, taxMethod: 'cash', booksStart: '2026-01-01', policies: '' })
  await command('chart.start', {})
  const state = await view('state'), acct = Object.fromEntries(state.accounts.map(a => [a.code, a.id]))
  const journal = await command('journal.save-draft', { date: '2026-09-15', memo: 'September settled design work and costs', lines: [
    { accountId: acct['1000'], debit: '10000.00' }, { accountId: acct['4000'], credit: '10000.00' },
    { accountId: acct['6000'], debit: '4000.00' }, { accountId: acct['1000'], credit: '4000.00' },
    { accountId: acct['6200'], debit: '2000.00' }, { accountId: acct['1000'], credit: '2000.00' },
  ] }); await command('journal.post', { id: journal.id, revision: journal.revision })
  const customer = await command('contact.save', { kind: 'customer', name: 'Cedar Studio', termsDays: 30 })
  const inv = await command('invoice.save-draft', { customerId: customer.id, issueDate: '2026-09-20', lines: [{ description: 'Unpaid design work', quantity: '1', rate: '2000.00', accountId: acct['4000'], taxCode: 'exempt' }] })
  await command('invoice.approve', { id: inv.id, revision: inv.revision }); await command('invoice.issue', { id: inv.id })
  const storageState = await owner.storageState()
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ storageState, viewport: { width, height: width === 390 ? 844 : 1000 } })
    const page = await context.newPage(), errors = []; page.on('pageerror', e => errors.push(String(e)))
    const name = `Studio margin ${width}`, summaryName = `Operating summary ${width}`
    const chooseTab = async tab => width === 390 ? page.getByLabel('Custom report view', { exact: true }).selectOption(tab) : page.getByRole('tab', { name: tab, exact: true }).click()
    const dates = async () => { await page.getByLabel('From', { exact: true }).fill('2026-09-01'); await page.getByLabel('To', { exact: true }).fill('2026-09-30') }
    await page.goto(`${app.origin}/app/reports?report=custom`)
    await page.getByRole('button', { name: 'New custom report', exact: true }).click()
    await page.getByLabel('Report name', { exact: true }).fill(name); await dates()
    await page.getByLabel('Group by', { exact: true }).selectOption('section')
    await page.getByLabel('Filter accounts', { exact: true }).selectOption([acct['4000'], acct['6000']])
    await page.getByLabel('Column Code', { exact: true }).uncheck()
    await page.getByRole('button', { name: 'Add section', exact: true }).click()
    await page.getByLabel('Row 1 reference', { exact: true }).fill('revenue')
    await page.getByLabel('Row 1 label', { exact: true }).fill('Revenue')
    await page.getByLabel('Row 1 account types', { exact: true }).selectOption('income')
    await page.getByRole('button', { name: 'Add section', exact: true }).click()
    await page.getByLabel('Row 2 reference', { exact: true }).fill('direct-costs')
    await page.getByLabel('Row 2 label', { exact: true }).fill('Direct costs')
    await page.getByLabel('Row 2 accounts', { exact: true }).selectOption(acct['6000'])
    await page.getByRole('button', { name: 'Add formula', exact: true }).click()
    await page.getByLabel('Row 3 reference', { exact: true }).fill('gross')
    await page.getByLabel('Row 3 label', { exact: true }).fill('Gross profit')
    await page.getByLabel('Row 3 formula', { exact: true }).fill('row("revenue") - row("direct-costs")')
    await page.getByRole('button', { name: 'Add formula', exact: true }).click()
    await page.getByLabel('Row 4 reference', { exact: true }).fill('margin')
    await page.getByLabel('Row 4 label', { exact: true }).fill('Gross margin')
    await page.getByLabel('Row 4 formula', { exact: true }).fill('row("gross") / row("revenue") * 100')
    await page.getByLabel('Row 4 unit', { exact: true }).selectOption('percent')
    await page.getByRole('button', { name: 'Add note', exact: true }).click()
    await page.getByLabel('Row 5 note', { exact: true }).fill('Client expansion remains on plan.')
    await page.getByLabel('Report notes', { exact: true }).fill('Direct costs include contract design work.')
    await page.getByLabel('Share with accountant', { exact: true }).check()
    await page.screenshot({ path: `/tmp/sx-pantry-r12-report-editor-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Save custom report', exact: true }).click()
    await page.getByRole('heading', { name: new RegExp(`^${name} Cash basis`) }).waitFor()
    const grossRow = () => page.getByRole('row').filter({ has: page.getByText('Gross profit', { exact: true }) })
    const marginRow = () => page.getByRole('row').filter({ has: page.getByText('Gross margin', { exact: true }) })
    await grossRow().getByText('$6,000.00', { exact: true }).waitFor()
    await marginRow().getByText('60.00%', { exact: true }).waitFor()
    assert.equal(await page.getByRole('columnheader', { name: 'Code', exact: true }).count(), 0)
    const saved = (await view('custom-reports')).reports.find(r => r.name === name)
    assert.deepEqual(saved.shared_roles, ['accountant'])
    assert.deepEqual(saved.definition.filters.accountIds, [acct['4000'], acct['6000']])
    assert.equal(saved.definition.grouping, 'section')
    assert.equal(saved.definition.basis, undefined, 'declared default is retained as a default')
    await page.reload(); await page.getByRole('button', { name: `Open ${name}`, exact: true }).click()
    await page.getByText('Client expansion remains on plan.', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Edit custom report', exact: true }).click()
    await page.getByLabel('Report basis', { exact: true }).selectOption('accrual')
    await page.getByRole('button', { name: 'Save custom report', exact: true }).click()
    await page.getByRole('heading', { name: new RegExp(`^${name} Accrual basis`) }).waitFor()
    await grossRow().getByText('$8,000.00', { exact: true }).waitFor()
    await marginRow().getByText('66.67%', { exact: true }).waitFor()
    await marginRow().getByRole('button', { name: /^Open Gross margin Amount/ }).click()
    const drill = () => page.locator('.card').filter({ has: page.getByRole('heading', { name: /^Figure:/ }) })
    await drill().getByText('row("gross") / row("revenue") * 100', { exact: true }).waitFor()
    await drill().getByText('$8,000.00', { exact: true }).waitFor()
    await drill().getByText('Accrual basis · 2026-09-01 to 2026-09-30', { exact: true }).first().waitFor()
    const figureJson = await context.request.get(new URL(await drill().getByRole('link', { name: 'Export figure JSON', exact: true }).getAttribute('href'), app.origin).href)
    assert.equal(figureJson.status(), 200)
    const formula = await figureJson.json()
    assert.equal(formula.value, 66.67); assert.equal(formula.unit, 'percent')
    assert.deepEqual(formula.context.filters.accountIds, [acct['4000'], acct['6000']])
    assert.equal(formula.context.reportId, saved.id)
    assert.equal(await drill().getByRole('link', { name: 'Export source lines CSV', exact: true }).count(), 0, 'a formula exports its explanation, not invented additive rows')
    await page.screenshot({ path: `${evidence}/custom-formula-${width}.png`, fullPage: true })
    await drill().getByRole('button', { name: 'Open operand Gross profit', exact: true }).click()
    await drill().getByRole('button', { name: 'Open operand Revenue', exact: true }).click()
    await drill().getByText('Adds up to the report figure', { exact: true }).waitFor()
    const invoiceLink = drill().getByRole('link', { name: `Invoice ${inv.number} · Cedar Studio`, exact: true })
    const leafExport = drill().getByRole('link', { name: 'Export source lines CSV', exact: true })
    const source = await context.request.get(new URL(await leafExport.getAttribute('href'), app.origin).href)
    assert.equal(source.status(), 200)
    const parsed = (await source.text()).trim().split('\r\n').map(line => [...line.matchAll(/"((?:[^"]|"")*)"(?:,|$)/g)].map(m => m[1].replaceAll('""', '"')))
    assert.equal(parsed.slice(1).reduce((sum, row) => sum + Number(row[5]), 0), 1200000)
    assert.equal(JSON.parse(parsed[1][11]).reportId, saved.id)
    await invoiceLink.waitFor()
    const recordContext = new URL(await invoiceLink.getAttribute('href'), app.origin).searchParams
    assert.equal(recordContext.get('customId'), saved.id)
    assert.deepEqual(JSON.parse(recordContext.get('origin')).filters.accountIds, [acct['4000'], acct['6000']])
    assert.equal(new URL(await invoiceLink.getAttribute('href'), app.origin).searchParams.get('record'), `invoice:${inv.id}`)
    await page.screenshot({ path: `${evidence}/custom-lines-${width}.png`, fullPage: true })
    await invoiceLink.click()
    await page.getByRole('heading', { name: `Invoice ${inv.number} · Cedar Studio`, exact: true }).waitFor()
    await page.locator('td[data-label="Line"]').getByText('Unpaid design work', { exact: true }).waitFor()
    const nativeExport = await context.request.get(new URL(await page.getByRole('link', { name: 'Export record JSON', exact: true }).getAttribute('href'), app.origin).href)
    const exportedRecord = await nativeExport.json()
    assert.equal(exportedRecord.context.customId, saved.id)
    assert.equal(JSON.parse(exportedRecord.context.origin).node, recordContext.get('node'))
    await page.screenshot({ path: `${evidence}/custom-record-${width}.png`, fullPage: true })
    await page.getByRole('link', { name: 'Back to the figure', exact: true }).click()
    await drill().getByText('Adds up to the report figure', { exact: true }).waitFor()
    await page.screenshot({ path: `${evidence}/custom-return-${width}.png`, fullPage: true })
    await drill().getByRole('button', { name: 'Close figure', exact: true }).click()
    await page.getByRole('button', { name: `Open ${name}`, exact: true }).click()
    await page.getByRole('row').filter({ has: page.getByText('Direct costs', { exact: true }) }).getByRole('button', { name: /^Open Direct costs Amount/ }).click()
    await drill().getByText('Adds up to the report figure', { exact: true }).waitFor()
    await drill().getByText('$4,000.00', { exact: true }).first().waitFor()
    await drill().getByRole('link', { name: /Journal/ }).first().waitFor()
    await drill().getByRole('button', { name: 'Close figure', exact: true }).click()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `/tmp/sx-pantry-r12-report-result-${width}.png`, fullPage: true })
    await page.locator('.card').filter({ has: page.getByRole('heading', { name: new RegExp(`^${name} Accrual basis`) }) }).screenshot({ path: `/tmp/sx-pantry-r12-report-card-${width}.png` })
    // The custom report shows its range and opens its source report on the same basis and range.
    const resultCard = page.locator('.card').filter({ has: page.getByRole('heading', { name: new RegExp(`^${name} Accrual basis`) }) })
    await resultCard.getByText(/^2026-09-01 to 2026-09-30/).waitFor()
    const sourceLink = resultCard.getByRole('link', { name: 'Open source report', exact: true })
    assert.deepEqual(Object.fromEntries(new URL(await sourceLink.getAttribute('href'), app.origin).searchParams), { report: 'profit-and-loss', from: '2026-09-01', to: '2026-09-30', basis: 'accrual' })
    await sourceLink.click()
    await page.getByRole('heading', { name: /^Profit and loss Accrual basis/ }).waitFor()
    assert.deepEqual([await page.locator('#r-from').inputValue(), await page.locator('#r-to').inputValue()], ['2026-09-01', '2026-09-30'])
    await page.screenshot({ path: `/tmp/sx-pantry-r13-report-source-${width}.png`, fullPage: true })
    await page.goto(`${app.origin}/app/reports?report=custom`)
    await page.getByText(/^Personal reports and packages are visible to you and the owner/).waitFor()
    const underlying = await view('reports/profit-and-loss?from=2026-09-01&to=2026-09-30&basis=accrual')
    assert.equal(underlying.totalIncome - underlying.expenses.find(a => a.id === acct['6000']).amount, 800000)
    await page.getByRole('button', { name: 'New custom report', exact: true }).click()
    await page.getByLabel('Report name', { exact: true }).fill(summaryName); await dates()
    await page.getByLabel('Report basis', { exact: true }).selectOption('cash')
    await page.getByLabel('Group by', { exact: true }).selectOption('section')
    await page.getByLabel('Share with accountant', { exact: true }).check()
    await page.getByRole('button', { name: 'Save custom report', exact: true }).click()
    await page.getByRole('heading', { name: new RegExp(`^${summaryName} Cash basis`) }).waitFor()
    await chooseTab('Management packages')
    await page.getByRole('button', { name: 'New management package', exact: true }).click()
    await page.getByLabel('Package name', { exact: true }).fill(`September pack ${width}`)
    await page.getByLabel('Cover text', { exact: true }).fill(`September management review ${width}`)
    await page.getByLabel(`Include ${name}`, { exact: true }).check()
    await page.getByLabel(`Include ${summaryName}`, { exact: true }).check()
    await page.getByLabel('Commentary', { exact: true }).fill('Strong recurring design demand.')
    await page.getByLabel('Share with accountant', { exact: true }).check()
    await page.screenshot({ path: `/tmp/sx-pantry-r12-package-editor-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Save management package', exact: true }).click()
    await page.getByRole('link', { name: 'Download management package PDF', exact: true }).waitFor()
    await page.getByText('Strong recurring design demand.', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `/tmp/sx-pantry-r12-package-result-${width}.png`, fullPage: true })
    const link = page.getByRole('link', { name: 'Download management package PDF', exact: true })
    const response = await context.request.get(new URL(await link.getAttribute('href'), app.origin).href)
    assert.equal(response.status(), 200)
    const pdfBytes = await response.body(), pdf = pdfBytes.toString('latin1')
    await writeFile(`/tmp/sx-pantry-r12-management-${width}.pdf`, pdfBytes)
    for (const text of [`September management review ${width}`, name, summaryName, 'Strong recurring design demand.', 'Cash basis', 'Accrual basis', '8,000.00', '66.67']) assert.ok(pdf.includes(text), `package contains ${text}`)
    assert.ok((pdf.match(/\/Type \/Page\b/g) ?? []).length >= 4)
    const [download] = await Promise.all([page.waitForEvent('download'), link.click()])
    assert.equal(await download.failure(), null)
    assert.equal((await readFile(await download.path())).subarray(0, 5).toString(), '%PDF-')
    assert.deepEqual(errors, [], `no page errors at ${width}`)
    await context.close()
  }
})
