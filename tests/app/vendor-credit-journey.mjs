import assert from 'node:assert/strict'

// Extend the existing credential journey with the owner-to-sibling vendor-return path.
export async function vendorCreditJourney({ page, context, command, acct, width, origin }) {
  const vendor = await command('contact.save', { kind: 'vendor', name: `Harbor Ceramics ${width}` })
  const bill = await command('bill.save', { vendorId: vendor.id, reference: `HC-${width}`, billDate: '2026-10-17', post: true, lines: [{ description: 'Ceramic mugs', accountId: acct['6100'], amount: '100.00' }] })
  const name = 'Pier vendor returns ' + width
  await page.getByLabel('Integration name', { exact: true }).fill(name)
  await page.getByRole('checkbox', { name: /Vendor credits vendor-credits:write/ }).check()
  await page.getByRole('checkbox', { name: /Post approved sibling records post/ }).check()
  await page.getByText('How scopes work', { exact: true }).click()
  await page.getByText('Vendor credits and their allocations also need both', { exact: false }).waitFor()
  const created = page.waitForResponse(r => r.url().endsWith('/api/pantry/command/integration.create') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Create integration credential', exact: true }).click()
  const response = await created; assert.equal(response.status(), 200)
  const credential = await response.json()
  assert.deepEqual(credential.scopes, ['vendor-credits:write', 'post'])
  await page.getByRole('button', { name: 'I saved it', exact: true }).click()
  const path = origin + '/api/pantry/integration/v1/vendor-credits'
  const headers = { authorization: `Bearer ${credential.token}`, 'idempotency-key': 'synthetic-pantry-' + width }
  const body = { vendorId: vendor.id, reference: `HC-RETURN-${width}`, date: '2026-10-18', amount: '40.00', accountId: acct['6100'], allocations: [{ targetId: bill.id, amount: '10.00' }] }
  const posted = await context.request.post(path, { headers, data: body })
  assert.equal(posted.status(), 200); const credit = await posted.json()
  assert.equal(credit.unallocated_cents, 3000)
  assert.equal((await (await context.request.post(path, { headers, data: body })).json()).id, credit.id)
  await page.getByRole('button', { name: 'Refresh integrations', exact: true }).click()
  await page.getByRole('table', { name: 'Recent integration API calls', exact: true }).getByText('POST /api/pantry/integration/v1/vendor-credits', { exact: true }).first().waitFor()
  assert.equal(await page.locator('code.token').count(), 0)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (process.env.PANTRY_PROOF_DIR) await page.screenshot({ path: `${process.env.PANTRY_PROOF_DIR}/vendor-credit-settings-${width}.png`, fullPage: true })
  await page.goto(origin + '/app/sales')
  if (width === 1440) await page.getByRole('tab', { name: 'Payments', exact: true }).click()
  else await page.getByLabel('Show', { exact: true }).selectOption('Payments')
  const row = page.getByRole('row').filter({ has: page.getByText(body.reference, { exact: true }) })
  await row.getByText('$30.00', { exact: false }).waitFor()
  await row.getByRole('button', { name: 'Apply credit', exact: true }).click()
  await page.getByLabel('Application date', { exact: true }).fill('2026-10-19')
  await page.getByRole('group', { name: 'Apply credit to these bills', exact: true }).getByRole('textbox').fill('30.00')
  const applied = page.waitForResponse(r => r.url().endsWith('/api/pantry/command/vendor-credit.allocate') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Apply vendor credit', exact: true }).click()
  assert.equal((await applied).status(), 200)
  await row.getByText('$0.00', { exact: true }).waitFor()
  assert.equal(await row.getByRole('button', { name: 'Apply credit', exact: true }).count(), 0)
  const readback = await context.request.get(path + '/' + credit.id, { headers })
  assert.equal(readback.status(), 200)
  const settled = await readback.json(); assert.equal(settled.unallocated_cents, 0); assert.equal(settled.allocations.length, 2)
  assert.equal((await (await context.request.get(origin + '/api/pantry/sales')).json()).bills.find(b => b.id === bill.id).open_cents, 6000)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (process.env.PANTRY_PROOF_DIR) await page.screenshot({ path: `${process.env.PANTRY_PROOF_DIR}/vendor-credit-applied-${width}.png`, fullPage: true })
  await page.goto(origin + '/app/settings/api')
  const credentialRow = page.getByRole('table', { name: 'Integration credentials', exact: true }).getByRole('row').filter({ hasText: name })
  await credentialRow.getByRole('button', { name: 'Revoke', exact: true }).click()
  await credentialRow.getByText('Revoked', { exact: true }).waitFor()
  assert.equal((await context.request.get(path + '/' + credit.id, { headers })).status(), 401)
  if (process.env.PANTRY_PROOF_DIR) await page.screenshot({ path: `${process.env.PANTRY_PROOF_DIR}/vendor-credit-revoked-${width}.png`, fullPage: true })
}
