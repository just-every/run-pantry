import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'

export async function refundsBrowser({page,width,origin,command,view,customer,acct,bank}) {
  const proof=process.env.PANTRY_PROOF_DIR
  if(proof)await mkdir(proof,{recursive:true})
  let inv=await command('invoice.save-draft',{customerId:customer.id,issueDate:'2026-10-01',lines:[{description:'Cedar final design',quantity:'1',rate:'100',accountId:acct['4000'],taxCode:'exempt'}]})
  await command('invoice.approve',{id:inv.id,revision:inv.revision});inv=await command('invoice.issue',{id:inv.id})
  const payment=await command('payment.record',{direction:'received',contactId:customer.id,date:'2026-10-10',bankAccountId:bank.id,amount:'300',reference:`Cedar overpayment ${width}`,allocations:[{targetId:inv.id,amount:'100'}]})
  await page.goto(`${origin}/app/sales?tab=payments`)
  await page.getByRole('row').filter({has:page.getByText('$300.00',{exact:true})}).last().click()
  const panel=page.locator('section.card').filter({has:page.getByRole('heading',{name:'Customer balance refund',exact:true})})
  await panel.locator('summary',{hasText:'Refund customer balance'}).click()
  await panel.getByLabel('Refund date',{exact:true}).fill('2026-10-30')
  await panel.getByLabel('Refund bank account',{exact:true}).selectOption(bank.id)
  await panel.getByLabel('Refund reason',{exact:true}).fill('Customer requested their excess payment back')
  await panel.getByRole('button',{name:'Prepare refund',exact:true}).click()
  await panel.getByRole('button',{name:'Approve refund',exact:true}).click()
  if(proof)await panel.screenshot({path:`${proof}/refund-approved-${width}.png`})
  await panel.getByRole('button',{name:'Record refund',exact:true}).click()
  await panel.getByText('succeeded',{exact:true}).waitFor()
  const sales=await view('sales'),refund=sales.refunds.find(r=>r.source_id===payment.id)
  assert.equal(refund.amount_cents,20000);assert.equal(refund.status,'succeeded')
  assert.equal(sales.invoices.find(i=>i.id===inv.id).open_cents,0)
  assert.equal(sales.payments.find(p=>p.id===payment.id).unallocated_cents,0)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  if(proof)await page.screenshot({path:`${proof}/refund-recorded-${width}.png`,fullPage:true})
  await panel.getByRole('link',{name:'View refund entry',exact:true}).click()
  await page.getByRole('heading',{name:/Journal entry/}).first().waitFor()
  if(proof)await page.screenshot({path:`${proof}/refund-entry-${width}.png`,fullPage:true})
  await page.goto(`${origin}/app/sales?tab=contacts&customer=${customer.id}`)
  await page.getByRole('heading',{name:`${customer.name} · customer history`,exact:true}).waitFor()
  await page.getByRole('link',{name:'Refund Customer refund',exact:true}).first().waitFor()
  if(proof)await page.screenshot({path:`${proof}/refund-history-${width}.png`,fullPage:true})
}

export async function voidBrowser({page,width,origin,command,view,customer,acct}) {
  let inv=await command('invoice.save-draft',{customerId:customer.id,issueDate:'2026-10-01',lines:[{description:'Cancelled design booking',quantity:'1',rate:'450',accountId:acct['4000'],taxCode:'exempt'}]})
  await command('invoice.approve',{id:inv.id,revision:inv.revision});inv=await command('invoice.issue',{id:inv.id})
  await command('invoice.send',{id:inv.id})
  const sent=(await view('sales')).invoices.find(i=>i.id===inv.id),link=`${origin}/i/${sent.link_token}`
  await page.goto(`${origin}/app/sales?invoice=${inv.id}`)
  const form=page.locator('details').filter({has:page.locator('summary',{hasText:'Void invoice'})})
  await form.locator('summary').click()
  await form.getByLabel('Void date',{exact:true}).fill('2026-10-30')
  await form.getByLabel('Void reason',{exact:true}).fill('Customer cancelled before any work or payment')
  await form.getByRole('button',{name:'Void invoice',exact:true}).click()
  await page.getByText('Voided',{exact:true}).first().waitFor()
  await page.getByRole('link',{name:'View linked reversal',exact:true}).waitFor()
  assert.equal((await view('sales')).invoices.find(i=>i.id===inv.id).open_cents,0)
  assert.equal((await page.request.get(link)).status(),404)
  assert.equal(await page.getByRole('button',{name:'Send invoice',exact:true}).count(),0)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  if(process.env.PANTRY_PROOF_DIR)await page.screenshot({path:`${process.env.PANTRY_PROOF_DIR}/invoice-void-${width}.png`,fullPage:true})
  await page.getByRole('link',{name:'View linked reversal',exact:true}).click()
  await page.getByRole('heading',{name:/Journal entry/}).first().waitFor()
  if(process.env.PANTRY_PROOF_DIR)await page.screenshot({path:`${process.env.PANTRY_PROOF_DIR}/invoice-void-reversal-${width}.png`,fullPage:true})
  await page.goto(`${origin}/app/sales?tab=contacts&customer=${customer.id}`)
}
