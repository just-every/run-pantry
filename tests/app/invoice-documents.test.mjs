import test from 'node:test'
import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { chromium } from '@playwright/test'
import { providerWorker } from './provider-worker.mjs'
import { TOKEN } from './worker.mjs'

test('INVOICE-001 owner edits branded templates and sequence, previews real invoices, selects customer defaults and shares retained PDFs at 1440 and 390', async t => {
  const app = await providerWorker({ bindings: {}, outbound: async request => { throw new Error(`Unexpected provider request: ${new URL(request.url).hostname}`) } })
  t.after(() => app.close())
  const browser = await chromium.launch({ headless: true, args: ['--use-mock-keychain', '--password-store=basic'] }); t.after(() => browser.close())
  const owner = await browser.newContext(); t.after(() => owner.close())
  assert.equal((await owner.request.post(`${app.origin}/auth/bootstrap`, { headers: { origin: app.origin }, data: { token: TOKEN, displayName: 'Olivia Owner' }, maxRedirects: 0 })).status(), 303)
  await owner.request.post(`${app.origin}/setup`, { headers: { origin: app.origin }, form: { confirm: 'yes' }, maxRedirects: 0 })
  const command = async (op, data) => { const r = await owner.request.post(`${app.origin}/api/pantry/command/${op}`, { headers: { origin: app.origin }, data }); assert.equal(r.status(), 200, `${op}: ${await r.text()}`); return r.json() }
  const view = async path => { const r = await owner.request.get(`${app.origin}/api/pantry/${path}`); assert.equal(r.status(), 200, await r.text()); return r.json() }
  await command('entity.save', { legalName: 'Juniper Lane Design LLC', entityType: 'single-member-llc', state: 'NY', fiscalYearStart: 1, taxMethod: 'cash', booksStart: '2026-01-01' })
  await command('chart.start', {})
  const state = await view('state'), income = state.accounts.find(a => a.code === '4000').id
  const storageState = await owner.storageState()
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ storageState, viewport: { width, height: width === 390 ? 844 : 1100 } })
    const page = await context.newPage(), errors = []; page.on('pageerror', e => errors.push(String(e)))
    const customer = await command('contact.save', { kind: 'customer', name: `Cedar invoice ${width}`, email: `cedar-${width}@example.test` })
    const other = await command('contact.save', { kind: 'customer', name: `Willow invoice ${width}`, email: `willow-${width}@example.test` })
    const logo = async color => Buffer.from(await page.evaluate(color => { const canvas = document.createElement('canvas'); canvas.width = 100; canvas.height = 40; const c = canvas.getContext('2d'); c.fillStyle = color; c.fillRect(0, 0, 100, 40); c.fillStyle = 'white'; c.font = 'bold 18px sans-serif'; c.fillText('JUNIPER', 6, 26); return canvas.toDataURL('image/jpeg').split(',')[1] }, color), 'base64')
    const templates = async () => { await page.goto(`${app.origin}/app/sales?tab=templates`); await page.getByRole('heading', { name: 'Invoice documents', exact: true }).waitFor() }
    await templates()
    const logoA = await logo('#174838'), logoB = await logo('#b15837')
    await page.getByLabel('Saved invoice template', { exact: true }).selectOption('standard')
    await page.getByRole('button', { name: 'Edit invoice template', exact: true }).click()
    await page.getByLabel('Template name', { exact: true }).fill(`Services ${width}`)
    await page.getByLabel('Document layout', { exact: true }).selectOption('classic')
    await page.getByLabel('Accent color', { exact: true }).fill('#174838')
    await page.getByLabel('Default invoice terms (days)', { exact: true }).fill('45')
    await page.getByLabel('Logo · JPEG, up to 100 KB', { exact: true }).setInputFiles({ name: 'services.jpg', mimeType: 'image/jpeg', buffer: logoA })
    await page.getByLabel('Business address on invoices', { exact: true }).fill('18 Cedar Street\nNew York NY 10001')
    await page.getByLabel('Remit to', { exact: true }).fill('Juniper Remittance\nPO Box 231')
    await page.getByLabel('Payment instructions', { exact: true }).fill('Bank transfer: use your invoice number as the reference.')
    await page.getByLabel('Template message', { exact: true }).fill(`Services engagement ${width}`)
    await page.getByLabel('Invoice footer', { exact: true }).fill('Thank you for supporting our studio.')
    if (await page.getByLabel('Field 1 key', { exact: true }).count() === 0) await page.getByRole('button', { name: 'Add custom field', exact: true }).click()
    await page.getByLabel('Field 1 key', { exact: true }).fill('po_number')
    await page.getByLabel('Field 1 label', { exact: true }).fill('PO number')
    await page.getByLabel('Field 1 default value', { exact: true }).fill('')
    await page.screenshot({ path: `/tmp/sx-pantry-r15-invoice-template-edit-${width}.png`, fullPage: true })
    await Promise.all([page.waitForResponse(r => r.url().includes('/command/invoice-template.save') && r.status() === 200), page.getByRole('button', { name: 'Save invoice template', exact: true }).click()])
    await page.getByRole('button', { name: 'Save invoice template', exact: true }).waitFor({ state: 'hidden' })
    const firstNumber = width === 1440 ? 231 : 331
    await page.getByLabel('Next invoice sequence number', { exact: true }).fill(String(firstNumber))
    await page.getByLabel('Business default invoice template', { exact: true }).selectOption('standard')
    await page.getByRole('button', { name: 'Save invoice defaults', exact: true }).click()
    await page.getByText(`Next automatic number: INV-${String(firstNumber).padStart(4, '0')}. Set the first unused number from your previous system.`, { exact: true }).waitFor()
    const makeInvoice = async (who, field, value) => {
      await page.goto(`${app.origin}/app/sales`)
      await page.getByRole('button', { name: 'Create invoice', exact: true }).click()
      await page.getByLabel('Customer', { exact: true }).selectOption(who.id)
      await page.getByLabel(field, { exact: true }).fill(value)
      await page.getByLabel('Issue date', { exact: true }).fill('2026-09-01')
      assert.equal(await page.getByLabel('Due date', { exact: true }).inputValue(), '2026-10-16')
      await page.getByLabel('Line 1 description', { exact: true }).fill(`Design services ${width}`)
      await page.getByLabel('Line 1 quantity', { exact: true }).fill('2')
      await page.getByLabel('Line 1 rate', { exact: true }).fill('250.00')
      await page.getByLabel('Line 1 income account', { exact: true }).selectOption(income)
      await page.getByLabel('Line 1 sales tax code', { exact: true }).selectOption('exempt')
      await page.screenshot({ path: `/tmp/sx-pantry-r15-invoice-draft-${width}-${field === 'PO number' ? 'services' : 'projects'}.png`, fullPage: true })
      await page.getByRole('button', { name: 'Save draft', exact: true }).click()
      await page.getByRole('button', { name: 'Approve', exact: true }).waitFor()
      const draft = (await view('sales')).invoices.filter(i => i.customer_id === who.id).sort((a, b) => b.number.localeCompare(a.number))[0]
      await page.getByRole('button', { name: 'Edit', exact: true }).click()
      await page.getByRole('heading', { name: 'Template preview on this invoice', exact: true }).waitFor()
      await page.screenshot({ path: `/tmp/sx-pantry-r15-invoice-saved-edit-${width}-${field === 'PO number' ? 'services' : 'projects'}.png`, fullPage: true })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      await page.getByRole('button', { name: 'Save draft', exact: true }).click()
      await page.getByRole('button', { name: 'Approve', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Approve', exact: true }).click()
      await page.getByRole('button', { name: 'Issue', exact: true }).click()
      await page.getByRole('button', { name: 'Send invoice', exact: true }).waitFor()
      return draft
    }
    const first = await makeInvoice(customer, 'PO number', `PO-${width}`)
    assert.equal(first.number, `INV-${String(firstNumber).padStart(4, '0')}`)
    await page.getByRole('button', { name: 'Send invoice', exact: true }).click()
    await page.getByText('Not sent: local run', { exact: true }).first().waitFor()
    const sent = (await view('sales')).invoices.find(i => i.id === first.id)
    const retained = await view(`invoice-documents/${first.id}/preview`)
    const anonymous = await browser.newContext({ viewport: { width, height: width === 390 ? 844 : 1100 } }), hosted = await anonymous.newPage()
    await hosted.goto(`${app.origin}/i/${sent.link_token}`)
    await hosted.getByText(`PO-${width}`, { exact: true }).waitFor()
    assert.equal(await hosted.locator('iframe[title="Issued invoice PDF"]').count(), 1)
    const download = await anonymous.request.get(`${app.origin}/i/${sent.link_token}/invoice.pdf`), bytes = await download.body()
    await writeFile(`/tmp/sx-pantry-r15-invoice-services-${width}.pdf`, bytes)
    assert.equal(createHash('sha256').update(bytes).digest('hex'), retained.sha256)
    assert.deepEqual(bytes, Buffer.from(retained.pdfBase64, 'base64'))
    assert.equal(await hosted.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await hosted.screenshot({ path: `/tmp/sx-pantry-r15-invoice-hosted-${width}.png`, fullPage: true })
    await anonymous.close()
    await templates()
    await page.getByRole('button', { name: 'New invoice template', exact: true }).click()
    await page.getByLabel('Template name', { exact: true }).fill(`Projects ${width}`)
    await page.getByLabel('Document layout', { exact: true }).selectOption('banner')
    await page.getByLabel('Accent color', { exact: true }).fill('#b15837')
    await page.getByLabel('Default invoice terms (days)', { exact: true }).fill('45')
    await page.getByLabel('Logo · JPEG, up to 100 KB', { exact: true }).setInputFiles({ name: 'projects.jpg', mimeType: 'image/jpeg', buffer: logoB })
    await page.getByLabel('Template message', { exact: true }).fill('Milestones for your project.')
    await page.getByRole('button', { name: 'Add custom field', exact: true }).click()
    await page.getByLabel('Field 1 key', { exact: true }).fill('project')
    await page.getByLabel('Field 1 label', { exact: true }).fill('Project reference')
    await page.getByLabel('Field 1 default value', { exact: true }).fill(`PROJECT-${width}`)
    await Promise.all([page.waitForResponse(r => r.url().includes('/command/invoice-template.save') && r.status() === 200), page.getByRole('button', { name: 'Save invoice template', exact: true }).click()])
    await page.getByRole('button', { name: 'Save invoice template', exact: true }).waitFor({ state: 'hidden' })
    const project = (await view('invoice-documents')).templates.find(t => t.name === `Projects ${width}`)
    await page.getByLabel('Invoice for template preview', { exact: true }).selectOption(first.id)
    await page.getByRole('heading', { name: 'Template preview on this invoice', exact: true }).waitFor()
    await page.getByText(`PROJECT-${width}`, { exact: true }).waitFor()
    assert.equal(await page.getByText(`PO-${width}`, { exact: true }).count(), 0)
    await page.screenshot({ path: `/tmp/sx-pantry-r15-invoice-project-preview-${width}.png`, fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.getByLabel('Customer for template default', { exact: true }).selectOption(customer.id)
    await page.getByLabel('Customer default invoice template', { exact: true }).selectOption(project.id)
    await Promise.all([page.waitForResponse(r => r.url().includes('/command/customer.invoice-template') && r.status() === 200), page.getByRole('button', { name: 'Save customer invoice template', exact: true }).click()])
    // Public read proves the saved default before starting the next invoice.
    const savedCustomer = (await view('state')).contacts.find(c => c.id === customer.id)
    assert.equal(savedCustomer.invoice_template_id, project.id)
    const second = await makeInvoice(customer, 'Project reference', `PROJECT-${width}`)
    assert.equal(second.document_template_id, project.id)
    const secondDoc = await view(`invoice-documents/${second.id}/preview`)
    assert.equal(secondDoc.document.logo.base64, logoB.toString('base64'))
    assert.equal(secondDoc.document.layout, 'banner')
    await writeFile(`/tmp/sx-pantry-r15-invoice-projects-${width}.pdf`, Buffer.from(secondDoc.pdfBase64, 'base64'))
    const otherDraft = await command('invoice.save-draft', { customerId: other.id, issueDate: '2026-09-01', customFields: { po_number: 'OTHER-PO' }, lines: [{ description: 'Other service', quantity: '1', rate: '100.00', accountId: income, taxCode: 'exempt' }] })
    assert.equal(otherDraft.document_template_id, 'standard')
    assert.equal((await view(`invoice-documents/${first.id}/preview`)).sha256, retained.sha256)
    assert.deepEqual(errors, [], `no page errors at ${width}`)
    await context.close()
  }
})
