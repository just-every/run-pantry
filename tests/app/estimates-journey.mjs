import { siblingEdge, siblingBrowser } from './estimate-siblings.mjs'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir } from 'node:fs/promises'
import { chromium, expect } from '@playwright/test'
import { providerWorker } from './provider-worker.mjs'
import { TOKEN } from './worker.mjs'

// Actual built Worker, native sign-in and money; only outgoing mail is faked.
export async function estimatesJourney(t) {
  const sibling = {}, mail = [], evidence = process.env.PANTRY_EVIDENCE_DIR || '/tmp/pantry-estimates'
  await mkdir(evidence, { recursive: true })
  const app = await providerWorker({ clock: true, bindings: { MAIL_PROVIDER: 'resend', MAIL_API_KEY: 'synthetic-pantry-1' }, outbound: async request => {
    if (['inkwell.example.test', 'platter.example.test'].includes(new URL(request.url).hostname)) return siblingEdge(request, sibling)
    assert.equal(new URL(request.url).hostname, 'api.resend.com')
    mail.push(await request.json()); return Response.json({ id: `synthetic-pantry-${mail.length}` })
  } }); t.after(() => app.close())
  const browser = await chromium.launch({ headless: true, args: ['--use-mock-keychain', '--password-store=basic'] }); t.after(() => browser.close())
  const owner = await browser.newContext(); t.after(() => owner.close())
  const { origin } = app, date = '2026-10-21'
  assert.equal((await owner.request.post(`${origin}/auth/bootstrap`, { headers: { origin }, data: { token: TOKEN, displayName: 'Rosa Rivera' }, maxRedirects: 0 })).status(), 303)
  assert.equal((await owner.request.post(`${origin}/setup`, { headers: { origin }, form: { confirm: 'yes' }, maxRedirects: 0 })).status(), 303)
  const command = async (op, data) => {
    const r = await owner.request.post(`${origin}/api/pantry/command/${op}`, { headers: { origin }, data })
    assert.equal(r.status(), 200, `${op}: ${await r.text()}`); return r.json()
  }
  const view = async path => { const r = await owner.request.get(`${origin}/api/pantry/${path}`); assert.equal(r.status(), 200, await r.text()); return r.json() }
  await command('entity.save', { legalName: 'Juniper Studio LLC', entityType: 'single-member-llc', state: 'NY', fiscalYearStart: 1, taxMethod: 'accrual', booksStart: '2026-01-01' })
  await command('chart.start', {})
  const state = await view('state'), accounts = Object.fromEntries(state.accounts.map(a => [a.code, a.id]))
  const bank = await command('bank-account.save', { name: 'Operating checking', institution: 'Juniper Bank', accountId: accounts['1000'], numberLast4: '4821', openingDate: '2026-01-01', openingBalance: '0' })
  const liability = await command('account.save', { code: '2310', name: 'Customer deposits held', type: 'liability', subtype: 'other' })
  const service = await command('item.save', { name: 'Brand and website project', kind: 'service', rate: '12000', accountId: accounts['4000'], taxCategory: 'non-taxable' })
  const validUntil = new Date(Date.now() + 2 * 86400000).toISOString().slice(0, 10)
  for (const width of [1440, 390]) {
    const customer = await command('contact.save', { kind: 'customer', name: `Cedar Workshop ${width}`, email: `synthetic-pantry-${width}@example.test` })
    const page = await owner.newPage(); await page.setViewportSize({ width, height: 1000 })
    const errors = []; page.on('pageerror', e => errors.push(String(e)))
    const shot = name => page.screenshot({ path: `${evidence}/estimate-${name}-${width}.png`, fullPage: true })
    await page.goto(`${origin}/app/sales?tab=estimates`)
    if (width === 1440) await expect(page.getByRole('heading', { name: 'New estimate', exact: true })).toBeVisible()
    else await page.getByRole('button', { name: 'Create estimate', exact: true }).click()
    await page.getByLabel('Customer', { exact: true }).selectOption(customer.id)
    await page.getByLabel('Estimate number', { exact: true }).fill(`EST-${width}`)
    await page.getByLabel('Estimate date', { exact: true }).fill(date)
    await page.getByLabel('Valid until', { exact: true }).fill(validUntil)
    await page.getByLabel('Line 1 product or service', { exact: true }).selectOption(service.id)
    await page.getByLabel('Memo on the estimate', { exact: true }).fill('Brand strategy, design and launch of the Cedar Workshop website.')
    await shot('editor')
    await page.getByRole('button', { name: 'Save estimate draft', exact: true }).click()
    await expect(page.getByRole('heading', { name: `${customer.name} · EST-${width}`, exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Estimate document preview', exact: true })).toBeVisible()
    await shot('draft')
    let estimate = (await view('estimates')).estimates.find(e => e.number === `EST-${width}`)
    assert.equal(estimate.total_cents, 1200000)
    assert.equal(estimate.validity.validUntil, validUntil)
    await expect(page.getByText(`${validUntil} (inclusive, America/New_York)`, { exact: true })).toBeVisible()
    await page.getByLabel('I reviewed this saved estimate revision and document.', { exact: true }).check()
    await page.getByRole('button', { name: 'Send estimate', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Retained sent estimate', exact: true })).toBeVisible()
    await shot('sent')
    estimate = await view(`estimates/${estimate.id}`)
    const sentPdf = await owner.request.get(`${origin}/api/pantry/estimates/${estimate.id}/pdf`)
    assert.equal(sentPdf.status(), 200)
    const message = mail.findLast(m => [m.to].flat().includes(customer.email))
    assert.ok(message)
    const publicPath = new URL(message.text.match(/http:\/\/[^\s]+\/e\/[A-Za-z0-9_-]+/)[0]).pathname
    const customerContext = await browser.newContext({ viewport: { width, height: 1000 } }); t.after(() => customerContext.close())
    const customerPage = await customerContext.newPage()
    await customerPage.goto(`${origin}${publicPath}`)
    await expect(customerPage.getByLabel('Your name', { exact: true })).toBeVisible()
    await expect(customerPage.getByText(`Typing your name and selecting Accept estimate signs revision ${estimate.revision} of this estimate electronically. Your name, time and IP address are kept as evidence.`, { exact: true })).toBeVisible()
    assert.equal(await customerPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `intent wording fits ${width}`)
    await customerPage.screenshot({ path: `${evidence}/estimate-customer-${width}.png`, fullPage: true })
    const publicPdf = await customerContext.request.get(`${origin}${publicPath}/estimate.pdf`)
    assert.equal(publicPdf.status(), 200); assert.deepEqual(await publicPdf.body(), await sentPdf.body())
    await customerPage.getByLabel('Your name', { exact: true }).fill('Casey Cedar')
    const acceptedResponse = customerPage.waitForResponse(r => r.url().endsWith('/accept') && r.request().method() === 'POST')
    await customerPage.getByRole('button', { name: 'Accept estimate', exact: true }).click()
    const accepted = await acceptedResponse
    await customerPage.screenshot({ path: `${evidence}/estimate-accept-result-${width}.png`, fullPage: true })
    assert.equal(accepted.status(), 200, await accepted.text())
    await expect(customerPage.getByRole('status').filter({ hasText: 'Accepted by Casey Cedar' })).toBeVisible()
    await customerPage.screenshot({ path: `${evidence}/estimate-accepted-${width}.png`, fullPage: true })
    const acceptedEstimate = await view(`estimates/${estimate.id}`)
    const acceptedPdf = await customerContext.request.get(`${origin}${publicPath}/estimate.pdf`)
    const acceptedBytes = await acceptedPdf.body()
    for (const fact of ['Casey Cedar', acceptedEstimate.acceptance.at, estimate.revision]) assert.ok(acceptedBytes.toString().includes(fact))
    assert.equal(createHash('sha256').update(acceptedBytes).digest('hex'), acceptedEstimate.accepted_pdf_sha256)
    assert.doesNotMatch(acceptedBytes.toString(), /127\.0\.0\.1/)
    const confirmation = mail.findLast(m => m.subject.startsWith('Accepted estimate '+estimate.number))
    assert.deepEqual(confirmation.to, [customer.email]); assert.ok(confirmation.text.includes(publicPath+'/estimate.pdf'))
    await page.goto(`${origin}/app/sales?tab=estimates&estimate=${estimate.id}`)
    await expect(page.getByRole('link', { name: 'Download accepted estimate PDF', exact: true })).toBeVisible()
    assert.deepEqual(await (await owner.request.get(`${origin}/api/pantry/estimates/${estimate.id}/accepted.pdf`)).body(), acceptedBytes)
    await shot('accepted-copy')
    await siblingBrowser(page, origin, estimate, customer, await sentPdf.body(), width, evidence, sibling)

    await page.goto(`${origin}/app/sales?tab=deposits`)
    await page.getByLabel('Deposit customer', { exact: true }).selectOption(customer.id)
    await page.getByLabel('Date received', { exact: true }).fill(date)
    await page.getByLabel('Deposit received amount', { exact: true }).fill('3000')
    await page.getByLabel('Bank account received into', { exact: true }).selectOption(bank.id)
    await page.getByLabel('Customer deposit liability account', { exact: true }).selectOption(liability.id)
    await page.getByLabel('How the deposit was paid', { exact: true }).selectOption('ach')
    await page.getByLabel('Deposit reference', { exact: true }).fill(`CEDAR-ADVANCE-${width}`)
    await page.getByRole('button', { name: 'Record customer deposit', exact: true }).click()
    await expect(page.locator('td[data-label="Reference"]').filter({ hasText: `CEDAR-ADVANCE-${width}` })).toBeVisible()
    await shot('deposit-held')
    const deposit = (await view('customer-deposits')).deposits.find(d => d.reference === `CEDAR-ADVANCE-${width}`)
    assert.equal(deposit.remaining_cents, 300000)
    for (const [index, mode, percentage, expected] of [[1, 'percent', '30', 360000], [2, 'percent', '40', 480000], [3, 'balance', '', 360000]]) {
      await page.goto(`${origin}/app/sales?tab=estimates&estimate=${estimate.id}`)
      await page.getByLabel('Invoice this estimate by', { exact: true }).selectOption(mode)
      if (percentage) await page.getByLabel('Percentage to invoice', { exact: true }).fill(percentage)
      await page.getByLabel('Invoice issue date', { exact: true }).fill(date)
      if (index === 1) {
        await page.getByLabel('Apply advance customer deposit', { exact: true }).selectOption(deposit.id)
        await page.getByLabel('Advance deposit to apply at invoice issue', { exact: true }).fill('3000')
      }
      await page.getByLabel('I reviewed this accepted estimate revision and the amount to invoice.', { exact: true }).check()
      await shot(`progress-${index}`)
      await page.getByRole('button', { name: 'Create invoice draft', exact: true }).click()
      await page.waitForURL(url => url.searchParams.has('invoice'))
      const invoiceId = new URL(page.url()).searchParams.get('invoice')
      await page.getByRole('button', { name: 'Approve', exact: true }).click()
      await page.getByRole('button', { name: 'Issue', exact: true }).click()
      await expect(page.getByRole('heading', { name: new RegExp(`^${customer.name} — INV-`) })).toBeVisible()
      await page.getByText(new RegExp(`${index === 1 ? '\\$600.00' : '\\$' + (expected / 100).toLocaleString('en-US') + '.00'} open`)).first().waitFor()
      const invoice = (await view('sales')).invoices.find(i => i.id === invoiceId)
      assert.equal(invoice.total_cents, expected); assert.equal(invoice.open_cents, expected - (index === 1 ? 300000 : 0))
      await shot(`invoice-${index}`)
    }
    await page.goto(`${origin}/app/sales?tab=estimates&estimate=${estimate.id}`)
    await expect(page.getByText('This estimate has been fully invoiced.', { exact: true })).toBeVisible()
    estimate = await view(`estimates/${estimate.id}`)
    assert.equal(estimate.billed_cents, 1200000); assert.equal(estimate.remaining_cents, 0)
    assert.equal((await view('customer-deposits')).deposits.find(d => d.id === deposit.id).remaining_cents, 0)
    await shot('complete')
    await page.goto(`${origin}/app/sales?tab=contacts&customer=${customer.id}`)
    await expect(page.getByRole('heading', { name: `${customer.name} · customer history`, exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: `Estimate EST-${width}`, exact: true })).toBeVisible()
    await shot('history')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `customer history fits ${width}`)
    await page.getByRole('link', { name: `Estimate EST-${width}`, exact: true }).click()
    await expect(page.getByRole('heading', { name: `${customer.name} · EST-${width}`, exact: true })).toBeVisible()
    const lastInvoice = estimate.conversions.at(-1)
    await page.getByRole('link', { name: lastInvoice.number, exact: true }).click()
    await expect(page.getByRole('heading', { name: `${customer.name} — ${lastInvoice.number}`, exact: true })).toBeVisible()
    await shot('converted-invoice-link')
    await page.goto(`${origin}/app/settings/connections`)
    const mailInventory = page.locator('#data-flows [data-service="mail"]')
    await mailInventory.locator('summary').click()
    await mailInventory.screenshot({ path: `${evidence}/estimate-mail-data-${width}.png` })
    for (const id of ['inkwell', 'platter']) {
      const inventory = page.locator(`#data-flows [data-service="${id}"]`)
      await inventory.locator('summary').click()
      await inventory.screenshot({ path: `${evidence}/estimate-${id}-data-${width}.png` })
    }
    await page.locator('#data-flows').screenshot({ path: `${evidence}/estimate-service-inventory-${width}.png` })
    // A page opened before lapse cannot accept once the saved window ends.
    const expiring = await command('estimate.save-draft', { ...estimate.input, number: `EXP-${width}`, validUntil })
    const expiringSent = await command('estimate.send', { id: expiring.id, revision: expiring.revision })
    await customerPage.goto(`${origin}${expiringSent.public_path}`)
    await expect(customerPage.getByLabel('Your name', { exact: true })).toBeVisible()
    const clock = { 'x-synthetic-pantry-clock': expiring.validity.expiresAt }
    await customerContext.setExtraHTTPHeaders(clock)
    const late = await customerContext.request.post(`${origin}${expiringSent.public_path}/accept`, { headers: { origin }, form: { name: 'Casey Cedar', revision: expiring.revision } })
    assert.equal(late.status(), 409, await late.text())
    await customerPage.reload()
    await expect(customerPage.getByRole('status').filter({ hasText: 'This estimate has expired.' })).toBeVisible()
    assert.equal(await customerPage.getByRole('button', { name: 'Accept estimate', exact: true }).count(), 0)
    await customerPage.screenshot({ path: `${evidence}/estimate-expired-customer-${width}.png`, fullPage: true })
    assert.equal(await customerPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await owner.setExtraHTTPHeaders(clock)
    await page.goto(`${origin}/app/sales?tab=estimates&estimate=${expiring.id}`)
    await expect(page.getByRole('status').filter({ hasText: 'This estimate has expired.' })).toBeVisible()
    assert.equal(await page.getByRole('button', { name: 'Send estimate again', exact: true }).isDisabled(), true)
    await shot('expired-owner')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.getByRole('button', { name: 'Edit estimate', exact: true }).click()
    assert.equal(await page.getByLabel('Valid until', { exact: true }).inputValue(), validUntil)
    await shot('expiry-edit')
    await owner.setExtraHTTPHeaders({})
    assert.deepEqual(errors, [])
    await page.close(); await customerContext.close()
  }
}
