import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {chromium,expect} from '@playwright/test'
import {providerWorker} from './provider-worker.mjs'
import {TOKEN} from './worker.mjs'

export async function dimensionsBrowser(t){
 const app=await providerWorker({bindings:{},outbound:async()=>{throw new Error('No provider request expected')}});t.after(()=>app.close())
 const browser=await chromium.launch({headless:true,args:['--use-mock-keychain','--password-store=basic']});t.after(()=>browser.close())
 const owner=await browser.newContext();t.after(()=>owner.close())
 const {origin}=app,proof=process.env.PANTRY_EVIDENCE_DIR||'/tmp/pantry-dimensions';await mkdir(proof,{recursive:true})
 assert.equal((await owner.request.post(origin+'/auth/bootstrap',{headers:{origin},data:{token:TOKEN,displayName:'Rosa Rivera'},maxRedirects:0})).status(),303)
 await owner.request.post(origin+'/setup',{headers:{origin},form:{confirm:'yes'},maxRedirects:0})
 const command=async(op,data)=>{const r=await owner.request.post(origin+'/api/pantry/command/'+op,{headers:{origin},data});assert.equal(r.status(),200,await r.text());return r.json()}
 const view=async(path)=>{const r=await owner.request.get(origin+'/api/pantry/'+path);assert.equal(r.status(),200,await r.text());return r.json()}
 await command('entity.save',{legalName:'Juniper Studio LLC',entityType:'single-member-llc',state:'NY',fiscalYearStart:1,taxMethod:'accrual',booksStart:'2026-01-01'})
 await command('chart.start',{})
 const state=await view('state'),acct=Object.fromEntries(state.accounts.map(a=>[a.code,a.id]))
 const vendor=await command('contact.save',{kind:'vendor',name:'Brightline Software'}),customer=await command('contact.save',{kind:'customer',name:'Cedar Workshop'})
 for(const width of [1440,390]){
  const page=await owner.newPage();await page.setViewportSize({width,height:1000})
  const errors=[];page.on('pageerror',e=>errors.push(String(e)))
  const shot=async(name)=>{assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`${name} fits ${width}`);await page.screenshot({path:`${proof}/dimensions-${name}-${width}.png`,fullPage:true})}
  await page.goto(origin+'/app/settings')
  const section=page.getByRole('heading',{name:'Classes, locations and projects',exact:true}).locator('..').locator('..')
  for(const name of ['Enable classes','Enable locations','Enable projects'])await section.getByLabel(name,{exact:true}).check()
  await section.getByRole('button',{name:'Save dimension settings',exact:true}).click()
  for(const [kind,name] of [['class',`Studio ${width}`],['location',`New York ${width}`],['project',`Cedar website ${width}`]]){
   await section.getByLabel('Dimension kind',{exact:true}).selectOption(kind)
   await section.getByLabel('Dimension name',{exact:true}).fill(name)
   await section.getByRole('button',{name:'Add dimension value',exact:true}).click()
   await expect(section.getByRole('cell',{name,exact:true})).toBeVisible()
  }
  await section.getByText('Required dimensions by account',{exact:true}).click()
  const requirement=section.locator('form').filter({has:page.getByRole('button',{name:'Save requirements for 6200',exact:true})})
  await requirement.getByLabel('Require class',{exact:true}).check()
  await requirement.getByRole('button',{name:'Save requirements for 6200',exact:true}).click()
  await section.screenshot({path:`${proof}/dimensions-settings-${width}.png`})
  await page.goto(origin+'/app/sales?tab=bills')
  const billForm=page.locator('form').filter({has:page.getByRole('button',{name:'Save bill',exact:true})})
  await billForm.getByLabel('Vendor',{exact:true}).selectOption(vendor.id)
  await billForm.getByLabel("Vendor's invoice number",{exact:true}).fill(`DIM-${width}`)
  await billForm.getByLabel('Bill date',{exact:true}).fill('2026-09-15')
  await billForm.getByLabel('Line 1 description',{exact:true}).fill('Website design software')
  await billForm.getByLabel('Line 1 account',{exact:true}).selectOption(acct['6200'])
  await billForm.getByLabel('Line 1 amount',{exact:true}).fill('400')
  await billForm.getByRole('button',{name:'Save bill',exact:true}).click()
  await expect(billForm.getByRole('alert')).toContainText('required dimension')
  await shot('bill-refused')
  for(const [kind,name] of [['class',`Studio ${width}`],['location',`New York ${width}`],['project',`Cedar website ${width}`]])await billForm.getByLabel(`Line 1 ${kind}`,{exact:true}).selectOption(name)
  await shot('bill-coded')
  await billForm.getByRole('button',{name:'Save bill',exact:true}).click()
  await expect(page.getByRole('cell',{name:`DIM-${width}`,exact:true})).toBeVisible()
  const bill=(await view('sales')).bills.find(b=>b.reference===`DIM-${width}`)
  await command('bill.record',{id:bill.id,revision:bill.revision})
  await page.goto(origin+'/app/sales?tab=invoices')
  await page.getByRole('button',{name:'Create invoice',exact:true}).click()
  await page.getByLabel('Customer',{exact:true}).selectOption(customer.id)
  await page.getByLabel('Issue date',{exact:true}).fill('2026-09-15')
  await page.getByLabel('Line 1 description',{exact:true}).fill(`Website design ${width}`)
  await page.getByLabel('Line 1 rate',{exact:true}).fill('1200')
  await page.getByLabel('Line 1 sales tax code',{exact:true}).selectOption('exempt')
  for(const [kind,name] of [['class',`Studio ${width}`],['location',`New York ${width}`],['project',`Cedar website ${width}`]])await page.getByLabel(`Line 1 ${kind}`,{exact:true}).selectOption(name)
  await shot('invoice-coded')
  await page.getByRole('button',{name:'Save draft',exact:true}).click()
  await page.getByRole('button',{name:'Approve',exact:true}).click();await page.getByRole('button',{name:'Issue',exact:true}).click()
  await page.goto(origin+'/app/books')
  await page.getByRole('button',{name:'New journal entry',exact:true}).click()
  await page.getByLabel('Entry date',{exact:true}).fill('2026-09-18')
  await page.getByLabel('Description',{exact:true}).fill(`Project stationery ${width}`)
  await page.getByLabel('Line 1 account',{exact:true}).selectOption(acct['6300'])
  await page.getByLabel('Line 1 debit',{exact:true}).fill('20')
  await page.getByLabel('Line 1 class',{exact:true}).selectOption(`Studio ${width}`)
  await page.getByLabel('Line 1 project',{exact:true}).selectOption(`Cedar website ${width}`)
  await page.getByLabel('Line 2 account',{exact:true}).selectOption(acct['1000'])
  await page.getByLabel('Line 2 credit',{exact:true}).fill('20')
  await shot('journal-coded')
  await page.getByRole('button',{name:'Save draft',exact:true}).click()
  let journal=(await view('journal')).entries.find(e=>e.memo===`Project stationery ${width}`)
  await command('journal.post',{id:journal.id,revision:journal.revision})
  await page.goto(origin+'/app/reports?report=profit-and-loss&from=2026-09-01&to=2026-09-30&basis=accrual&columns=class')
  for(const kind of ['class','location','project']){
   await page.getByLabel('Columns',{exact:true}).selectOption(kind)
   const table=page.getByRole('table',{name:`Profit and loss · ${kind} · accrual basis`,exact:true})
   await expect(table).toBeVisible()
   const r=await view(`reports/profit-and-loss?from=2026-09-01&to=2026-09-30&basis=accrual&columns=${kind}`)
   const name=kind==='class'?`Studio ${width}`:kind==='location'?`New York ${width}`:`Cedar website ${width}`,col=r.columns.find(c=>c.label===name)
   assert.ok(col)
   await shot(`report-${kind}`)
   const href=new URL(await table.getByRole('rowheader',{name:'Net income',exact:true}).locator('..').getByRole('link').nth(r.columns.findIndex(c=>c.id===col.id)).getAttribute('href'),origin)
   const detail=await view('reports/detail?'+new URLSearchParams({report:'profit-and-loss',line:'net-income',from:'2026-09-01',to:'2026-09-30',basis:'accrual',columns:kind,column:col.id}))
   assert.equal(detail.ties,true)
   await page.goto(href.href);await expect(page.getByText('Adds up to the report figure',{exact:true})).toBeVisible();await shot(`sources-${kind}`)
   await page.goto(origin+`/app/reports?report=profit-and-loss&from=2026-09-01&to=2026-09-30&basis=accrual&columns=${kind}`)
  }
  assert.deepEqual(errors,[])
  await page.close()
 }
}
