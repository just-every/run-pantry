import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

export async function approvedAdjustmentsBrowser({ page, context, width, origin, command, view, customer, acct, bank }) {
  const receivables = async () => { const r = await context.request.get(origin + '/api/pantry/reports/receivables?to=2026-10-30'); assert.equal(r.status(), 200); return r.json() }
  const existing = (await view('state')).accounts.find(a => a.code === '6950')
  const badDebt = existing ?? await command('account.save', { code: '6950', name: 'Bad debts', type: 'expense' })
  const prepareSource = async (amount, early = false) => {
    const d = await command('invoice.save-draft', { customerId: customer.id, issueDate: '2026-09-01', dueDate: '2026-09-30', ...(early ? { earlyPayment: { percent: '2', days: '10' } } : {}), lines: [{ description: `Design adjustment ${width}`, quantity: '1', rate: amount, accountId: acct['4000'], taxCode: 'exempt' }] })
    await command('invoice.approve', { id: d.id, revision: d.revision })
    return command('invoice.issue', { id: d.id })
  }
  const proof = process.env.PANTRY_PROOF_DIR
  if (proof) await mkdir(proof, { recursive: true })
  const source = await prepareSource('120')
  await page.goto(`${origin}/app/sales?invoice=${source.id}`)
  const form = page.locator('details').filter({ has: page.locator('summary', { hasText: 'Prepare a write-off' }) })
  await form.locator('summary').click()
  await form.getByLabel('Write-off date', { exact: true }).fill('2026-10-30')
  await form.getByLabel('Bad-debt account', { exact: true }).selectOption(badDebt.id)
  await form.getByLabel('Write-off reason', { exact: true }).fill('Uncollectible after customer closure')
  if (proof) await page.screenshot({ path: `${proof}/writeoff-prepare-${width}.png`, fullPage: true })
  const preparing = page.waitForResponse(r => r.url().endsWith('/command/write-off.prepare'))
  await form.getByRole('button', { name: 'Prepare write-off credit', exact: true }).click()
  const response = await preparing
  assert.equal(response.status(), 200, await response.text())
  const credit = await response.json()
  assert.deepEqual([credit.total_cents, credit.write_off, credit.status], [12000, 1, 'draft'])
  await page.waitForURL(u => u.searchParams.get('invoice') === credit.id)
  await page.getByText('Bad-debt write-off ·', { exact: false }).waitFor()
  const card = page.locator('section.card').filter({ has: page.getByRole('heading', { name: new RegExp(credit.number) }) })
  await card.getByRole('button', { name: 'Approve', exact: true }).click()
  await card.getByRole('button', { name: 'Issue', exact: true }).click()
  await card.getByText('Applied', { exact: true }).waitFor()
  await page.getByText('Bad-debt write-off ·', { exact: false }).waitFor()
  await card.getByRole('heading').evaluate(el => window.scrollBy(0, el.getBoundingClientRect().top - 100))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (proof) await page.screenshot({ path: `${proof}/approved-writeoff-${width}.png` })
  let sales = await view('sales')
  assert.equal(sales.invoices.find(i => i.id === source.id).open_cents, 0)
  assert.equal((await receivables()).agrees, true)

  const settings = (await view('invoicing')).discounts.settings
  await command('discount-settings.save', { discountAccountId: badDebt.id, earlyAccountId: badDebt.id, revision: settings?.revision })
  const late = await prepareSource('1000', true)
  await command('payment.record', { direction: 'received', contactId: customer.id, date: '2026-10-30', amount: '1000', bankAccountId: bank.id, allocations: [{ targetId: late.id, amount: '1000' }] })
  await page.goto(`${origin}/app/sales?invoice=${late.id}`)
  const honor = page.locator('details').filter({ has: page.locator('summary', { hasText: 'Honor a late discount' }) })
  await honor.locator('summary').click()
  await honor.getByLabel('Honor date', { exact: true }).fill('2026-10-30')
  await honor.getByLabel('Reason for honoring the discount', { exact: true }).fill('Explicit goodwill credit after the window')
  if (proof) await page.screenshot({ path: `${proof}/late-discount-prepare-${width}.png`, fullPage: true })
  const honoring = page.waitForResponse(r => r.url().endsWith('/command/early-discount.prepare-late'))
  await honor.getByRole('button', { name: 'Prepare late discount credit', exact: true }).click()
  const honoredResponse = await honoring
  assert.equal(honoredResponse.status(), 200, await honoredResponse.text())
  const discount = await honoredResponse.json()
  await page.waitForURL(u => u.searchParams.get('invoice') === discount.id)
  await page.getByText('Early-payment discount honored after window ·', { exact: false }).waitFor()
  const discountCard = page.locator('section.card').filter({ has: page.getByRole('heading', { name: new RegExp(discount.number) }) })
  await discountCard.getByRole('button', { name: 'Approve', exact: true }).click()
  await discountCard.getByRole('button', { name: 'Issue', exact: true }).click()
  await discountCard.getByText('Unapplied credit', { exact: true }).waitFor()
  await discountCard.getByRole('heading').evaluate(el => window.scrollBy(0, el.getBoundingClientRect().top - 100))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (proof) await page.screenshot({ path: `${proof}/late-discount-honor-${width}.png` })
  sales = await view('sales')
  const posted = sales.invoices.find(i => i.id === discount.id)
  assert.equal(posted.status, 'issued'); assert.equal(posted.early_discount, 1); assert.equal(posted.write_off, 0)
  assert.equal(sales.invoices.find(i => i.id === late.id).open_cents, 0)
  assert.equal(posted.open_cents, 2000)
  const target = await prepareSource('200')
  await page.goto(`${origin}/app/sales?invoice=${discount.id}`)
  const applying = page.locator('details').filter({ has: page.locator('summary', { hasText: 'Apply customer credit' }) })
  await applying.locator('summary').click()
  await applying.getByLabel('Credit application date', { exact: true }).fill('2026-10-30')
  await applying.getByLabel(`${target.number} — $200.00 open`, { exact: true }).fill('20')
  if (proof) await page.screenshot({ path: `${proof}/customer-credit-prepare-${width}.png`, fullPage: true })
  const applied = page.waitForResponse(r => r.url().endsWith('/command/customer-credit.allocate'))
  await applying.getByRole('button', { name: 'Apply customer credit', exact: true }).click()
  const application = await applied
  assert.equal(application.status(), 200, await application.text())
  await discountCard.getByText('Applied', { exact: true }).waitFor()
  if (proof) await page.screenshot({ path: `${proof}/customer-credit-applied-${width}.png` })
  sales = await view('sales')
  assert.equal(sales.invoices.find(i => i.id === discount.id).open_cents, 0)
  assert.equal(sales.invoices.find(i => i.id === target.id).open_cents, 18000)
  assert.equal((await receivables()).agrees, true)
  await page.goto(`${origin}/app/sales?tab=contacts&customer=${customer.id}`)
}
