import assert from 'node:assert/strict'

/** Run on the built test Worker or an already signed-in review context. */
export async function checkJourney({ browser, owner, origin, runId = '' }) {
  const tag = runId ? `-${runId}` : ''
  const cmd = async (op, data) => { const r = await owner.request.post(`${origin}/api/pantry/command/${op}`, { headers: { origin }, data }); assert.equal(r.status(), 200, await r.text()); return r.json() }
  const view = async path => (await owner.request.get(`${origin}/api/pantry/${path}`)).json()
  if (!(await view('state')).accounts.length) {
  await cmd('entity.save', { legalName: 'Juniper Lane Design LLC', entityType: 'single-member-llc', state: 'NY', fiscalYearStart: 1, taxMethod: 'cash', booksStart: '2026-01-01', policies: 'Revenue when invoiced.' })
  await cmd('chart.start', {})
  }
  const state = await view('state'), acct = Object.fromEntries(state.accounts.map(a => [a.code, a.id]))
  const vendor = await cmd('contact.save', { kind: 'vendor', name: `Juniper Print Works${tag}`, termsDays: 30 })
  const signedIn = await owner.storageState()
  for (const [width, first] of [[1440, 6101], [390, 7101]]) {
    const context = await browser.newContext({ storageState: signedIn, viewport: { width, height: 1000 } }), page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(String(e)))
    const used = new Set((await view('state')).accounts.map(a => a.code)); let code = 1020; while (used.has(String(code))) code++
    const ledger = await cmd('account.save', { code: String(code), name: `Check account ${width}${tag}`, type: 'asset', subtype: 'bank' })
    const bank = await cmd('bank-account.save', { name: `Checking ${width}${tag}`, institution: 'Community Bank', accountId: ledger.id, numberLast4: String(width).padStart(4, '0'), openingDate: '2026-08-31', openingBalance: '0' })
    for (const [suffix, amount] of [['A', '125.25'], ['B', '280.10']]) await cmd('bill.save', { vendorId: vendor.id, reference: `PRINT-${width}-${suffix}${tag}`, billDate: '2026-09-01', post: true, lines: [{ description: 'Print work', accountId: acct['6000'], amount }] })
    await page.goto(`${origin}/app/bank?tab=checks`)
    await page.getByLabel('Check bank account', { exact: true }).selectOption(bank.id)
    const setup = page.getByRole('heading', { name: 'Check setup', exact: true }).locator('..').locator('..')
    await setup.getByLabel('Next check number', { exact: true }).fill(String(first))
    await setup.getByLabel('Bank format name', { exact: true }).fill('Bank check import')
    await setup.getByLabel('Bank-provided account identifier', { exact: true }).fill(`bank-reference-${width}`)
    await setup.getByLabel('Issue code', { exact: true }).fill('I')
    await setup.getByLabel('Void code', { exact: true }).fill('V')
    await setup.getByRole('button', { name: 'Save check setup', exact: true }).click()
    const alignmentPromise = context.waitForEvent('page')
    await page.getByRole('link', { name: 'Print alignment page', exact: true }).click()
    const alignment = await alignmentPromise; await alignment.waitForLoadState()
    assert.equal(await alignment.locator('.check-face.alignment').count(), 1)
    await alignment.emulateMedia({ media: 'print' })
    await alignment.pdf({ path: `/tmp/sx-pantry-r10-check-alignment-${width}.pdf`, preferCSSPageSize: true })
    await alignment.locator('.sheet').screenshot({ path: `/tmp/sx-pantry-r10-check-alignment-${width}.png` })
    await alignment.close()
    const write = page.getByRole('heading', { name: 'Write checks', exact: true }).locator('..').locator('..')
    await write.getByLabel('Check date', { exact: true }).fill('2026-09-02')
    for (const suffix of ['A', 'B']) await write.getByRole('checkbox', { name: `Pay bill PRINT-${width}-${suffix}${tag}`, exact: true }).check()
    await write.getByRole('button', { name: 'Issue checks', exact: true }).click()
    const batch = page.getByRole('heading', { name: `Checks ${first}–${first + 1}`, exact: true }).locator('..').locator('..')
    await batch.waitFor()
    const printPromise = context.waitForEvent('page')
    await batch.getByRole('link', { name: 'Print batch', exact: true }).click()
    const print = await printPromise; await print.waitForLoadState()
    assert.equal(await print.locator('.sheet').count(), 2)
    assert.equal(await print.locator('[data-field="number"]').allTextContents().then(v => v.join(',')), `${first},${first + 1}`)
    await print.emulateMedia({ media: 'print' })
    await print.pdf({ path: `/tmp/sx-pantry-r10-voucher-checks-${width}.pdf`, preferCSSPageSize: true })
    await print.locator('.sheet').first().screenshot({ path: `/tmp/sx-pantry-r10-voucher-check-${width}.png` })
    await print.close()
    const journalsBefore = (await view('journal')).entries.length
    await cmd('statement.import', { bankAccountId: bank.id, fileName: `printed-checks-${width}.csv`, content: `Posting Date,Description,Amount\n09/10/2026,CHECK ${first},-125.25\n09/10/2026,CHECK ${first + 1},-280.10\n`, opening: '0', closing: '-405.35', start: '2026-09-01', end: '2026-09-30', confirmLast4: bank.number_last4 })
    assert.equal((await view('journal')).entries.length, journalsBefore)
    await page.reload()
    await page.getByLabel('Check bank account', { exact: true }).selectOption(bank.id)
    await batch.getByText('Cleared', { exact: true }).first().waitFor()
    await write.getByLabel('Write as', { exact: true }).selectOption('expense')
    await write.getByLabel('Check date', { exact: true }).fill('2026-09-03')
    await write.getByLabel('Payee', { exact: true }).selectOption(vendor.id)
    await write.getByLabel('Expense account', { exact: true }).selectOption(acct['6000'])
    await write.getByLabel('Expense amount', { exact: true }).fill('35.00')
    await write.getByLabel('Expense description', { exact: true }).fill('Proof prints')
    await write.getByRole('button', { name: 'Issue checks', exact: true }).click()
    const third = page.getByRole('heading', { name: `Checks ${first + 2}–${first + 2}`, exact: true }).locator('..').locator('..')
    await third.getByRole('button', { name: `Void check ${first + 2}`, exact: true }).click()
    await third.getByLabel('Void date', { exact: true }).fill('2026-09-04')
    await third.getByLabel('Void reason', { exact: true }).fill('Spoiled check stock')
    await third.getByRole('button', { name: `Confirm void ${first + 2}`, exact: true }).click()
    await third.getByText('Spoiled check stock', { exact: false }).waitFor()
    await third.getByRole('button', { name: 'Export positive-pay CSV', exact: true }).click()
    const downloadEvent = page.waitForEvent('download')
    await third.getByRole('link', { name: 'Download positive-pay CSV', exact: true }).click()
    const download = await downloadEvent
    await download.saveAs(`/tmp/sx-pantry-r10-positive-pay-${width}.csv`)
    const current = (await view('checks')).batches.find(b => b.bank_account_id === bank.id && b.checks.some(c => c.number === first + 2))
    const csv = await (await owner.request.get(`${origin}/api/pantry/checks/exports/${current.exports[0].id}.csv`)).text()
    assert.ok(csv.includes(`"${first + 2}"`)); assert.ok(csv.includes('"V"'))
    await page.screenshot({ path: `/tmp/sx-pantry-r10-checks-${width}.png`, fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.deepEqual(errors, [])
    await context.close()
  }
}
